def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding='utf-8')

def _candidate(root: Path, relative: str, *, nmod: int = 0,
               k_header: str = 'LD, k10 (0,0,g), g=1/6') -> Path:
    directory = root / relative
    _write(directory / 'subgroup.cif', f'# generated by test\n# k point: {k_header}\ndata_a\n')
    _write(directory / 'data.isoviz', f'#comment\n!numberOfModulations {nmod}\n')
    _write(directory / 'topas.str', 'str\n')
    _write(directory / 'ISODISTORT_ complete modes details.html', '<html></html>\n')
    _write(directory / 'ISODISTORT_ complete modes details_files' / 'style.css', 'body{}\n')
    return directory

def _archive(tmp_path: Path) -> tuple[Path, Path]:
    archive = tmp_path / 'output_compare'
    method2 = archive / 'Parent.cif' / '官网' / 'Method2'
    _candidate(method2, 'flat_dir', k_header='LD, k10 (0,0,g), g=1/6')
    _candidate(method2, 'IR1/OPD1', k_header='LD, k10 (0,0,g), g=1/6')
    _write(method2 / 'Screenshot 2026-10-05 222306.png', 'png\n')
    for method in ('Method1', 'Method3', 'Method4'):
        _write(archive / 'Parent.cif' / '官网' / method / 'case-one' / 'subgroup.cif', 'x\n')
    return archive, method2

def test_fingerprint_is_deterministic_and_content_sensitive(tmp_path):
    root = tmp_path / 'tree'
    _write(root / 'a.txt', 'one\n')
    _write(root / 'nested' / 'b.bin', 'two\n')
    first = registrar.fingerprint_tree(root)
    assert first == registrar.fingerprint_tree(root)
    assert first['file_count'] == 2
    _write(root / 'a.txt', 'changed\n')
    assert registrar.fingerprint_tree(root)['aggregate_sha256'] != first['aggregate_sha256']
    (root / 'a.txt').unlink()
    assert registrar.fingerprint_tree(root)['file_count'] == 1

def test_candidate_inventory_requires_core_artifacts_and_reads_nmod(tmp_path):
    method2 = tmp_path / 'Method2'
    directory = _candidate(method2, 'LD1_C1')
    entry = registrar.inventory_candidate(directory, method2, nmod=0)
    assert entry['id'] == 'LD1_C1'
    assert entry['missing_files'] == []
    assert entry['number_of_modulations'] == 0
    assert entry['k_header'] == 'LD, k10 (0,0,g), g=1/6'
    assert entry['resource_dirs'][0]['file_count'] == 1
    assert set(entry['files']) == {
        'subgroup.cif', 'data.isoviz', 'topas.str',
        'ISODISTORT_ complete modes details.html'}
    (directory / 'topas.str').write_text('', encoding='utf-8')
    assert registrar.inventory_candidate(directory, method2)['missing_files'] == ['topas.str']
    with pytest.raises(registrar.RegistrationError):
        registrar.inventory_candidate(directory, method2, nmod=1)

def test_registration_scans_only_the_contracted_archive_subdir(tmp_path):
    archive = tmp_path
    method2 = archive / 'Parent.cif' / '官网' / 'Method2'
    _candidate(method2, 'LD1_C1')
    _candidate(method2, 'other/K_nmod0/other_candidate')
    _candidate(method2, 'X/nmod0/X1+_P1', k_header='X, k13 (1/2,1/2,0)')
    flat = registrar.method2_registration({
        'query_id': 'M2P-EU-LD', 'parent': 'Parent.cif', 'nmod': 0,
        'expected_candidates': 1, 'archive_subdir': '',
        'layout': 'flat', 'expected_k_header': 'LD, k10 (0,0,g), g=1/6',
        'action': 'register_only_no_download'}, archive)
    assert [row['id'] for row in flat['candidates']] == ['LD1_C1']
    x = registrar.method2_registration({
        'query_id': 'M2F-X', 'parent': 'Parent.cif', 'nmod': 0,
        'expected_candidates': 1, 'archive_subdir': 'X/nmod0',
        'layout': 'flat', 'expected_k_header': 'X, k13 (1/2,1/2,0)',
        'action': 'register_built_structure'}, archive)
    assert [row['id'] for row in x['candidates']] == ['X1+_P1']
    assert x['archive_path'].endswith('Method2/X/nmod0')

def test_registration_enforces_count_layout_and_k_header(tmp_path):
    archive = tmp_path
    method2 = archive / 'Parent.cif' / '官网' / 'Method2'
    _candidate(method2, 'LD1_C1')
    _candidate(method2, 'LD1_P1')
    contract = {
        'query_id': 'M2P-EU-LD',
        'parent': 'Parent.cif',
        'nmod': 0,
        'expected_candidates': 2,
        'layout': 'flat <IR>_<OPD>',
        'expected_k_header': 'LD, k10 (0,0,g), g=1/6',
        'action': 'register_only_no_download',
    }
    registration = registrar.method2_registration(contract, archive)
    assert registration['candidate_count'] == 2
    assert [row['id'] for row in registration['candidates']] == ['LD1_C1', 'LD1_P1']
    assert registration['candidates_fingerprint']['file_count'] > 0
    assert registration.get('submit_state_capture') is None
    with pytest.raises(registrar.RegistrationError, match='contract expects'):
        registrar.method2_registration(dict(contract, expected_candidates=3), archive)
    with pytest.raises(registrar.RegistrationError, match='disagree'):
        registrar.method2_registration(dict(contract, expected_k_header='other'), archive)

def test_registry_must_stay_outside_archive(tmp_path):
    archive, _method2 = _archive(tmp_path)
    registrar._ensure_outside_archive(tmp_path / 'registry.json', archive)
    with pytest.raises(registrar.RegistrationError, match='outside'):
        registrar._ensure_outside_archive(archive / 'registry.json', archive)

@pytest.mark.skipif(not registrar.DEFAULT_ARCHIVE_ROOT.is_dir(),
                    reason='local official archive is not available')
def test_local_archive_matches_registered_reuse_contract():
    committed = registrar.DEFAULT_OUTPUT
    assert committed.is_file(), 'reuse registry must be committed with the manifest'
    registered = registrar.json.loads(committed.read_text(encoding='utf-8'))
    rebuilt = registrar.build_registry()
    assert rebuilt['verdict'] == registered['verdict'] == 'pass'
    # Only the immutable reuse entries are compared: the Method 2/3/4 subtrees may
    # grow later through the pre-registered new download directories.
    for key in ('method2_registered_reuse', 'method2_nmod1_status'):
        assert rebuilt[key] == registered[key], key
