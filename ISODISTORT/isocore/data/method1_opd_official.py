def lookup_official_opd(
    parent_sg: int,
    irrep_label: str,
    opd_symbol: str,
    opd_dir_raw: str,
) -> dict[str, str | int] | None:
    """Return website OPD fields for this isotropy subgroup, if known."""
    table = METHOD1_OPD_OFFICIAL.get(int(parent_sg) if parent_sg else 0)
    if not table:
        return None
    irrep = (irrep_label or "").strip()
    opd = (opd_symbol or "").strip()
    direction = (opd_dir_raw or "").strip()
    hit = table.get((irrep, opd, direction))
    if hit is not None:
        return hit
    compact = direction.replace(" ", "")
    for (ir, op, d), val in table.items():
        if ir == irrep and op == opd and d.replace(" ", "") == compact:
            return val
    return None

