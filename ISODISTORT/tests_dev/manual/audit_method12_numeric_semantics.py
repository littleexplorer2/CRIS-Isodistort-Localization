def _mode_label_diagnostics(mode_labels: dict[str, Any]) -> dict[str, Any]:
    """Expose pretty-label collisions without treating internal keys as physics."""

    groups: dict[str, list[dict[str, str]]] = {}
    for internal, raw_pretty in mode_labels.items():
        pretty = str(raw_pretty)
        canonical = _canonical_label(pretty)
        groups.setdefault(canonical, []).append(
            {"internal_key": str(internal), "pretty_label": pretty}
        )
    collisions = [
        {"canonical_pretty_label": label, "columns": columns}
        for label, columns in sorted(groups.items())
        if len(columns) > 1
    ]
    return {
        "internal_mode_count": len(mode_labels),
        "unique_canonical_pretty_label_count": len(groups),
        "collision_group_count": len(collisions),
        "colliding_column_count": sum(len(group["columns"]) for group in collisions),
        "collisions": collisions,
        "interpretation": (
            "Each internal key is a distinct computed column. Repeated pretty labels are "
            "an export-label collision and must not reduce the numerical mode count."
        ),
    }


def _select_live_candidate(candidates: list[Any], selector: dict[str, Any]) -> Any:
    matches = []
    expected_basis = np.asarray(selector["basis"], dtype=float)
    expected_origin = np.asarray(selector["origin"], dtype=float)
    for candidate in candidates:
        if str(candidate.irrep_label) != selector["irrep"]:
            continue
        if str(candidate.opd_symbol) != selector["opd"]:
            continue
        if int(candidate.space_group_number) != int(selector["space_group_number"]):
            continue
        basis = np.asarray(candidate.basis_vectors, dtype=float)
        origin = np.asarray(candidate.origin, dtype=float)
        if basis.shape != (3, 3) or not np.allclose(basis, expected_basis, rtol=0.0, atol=1.0e-12):
            continue
        delta = origin - expected_origin
        if origin.shape != (3,) or not np.allclose(delta - np.rint(delta), 0.0, rtol=0.0, atol=1.0e-12):
            continue
        matches.append(candidate)
    if len(matches) != 1:
        records = [_candidate_record(candidate) for candidate in candidates]
        raise RuntimeError(
            f"live selector must identify exactly one candidate, found {len(matches)}; "
            f"selector={selector!r}; candidate_count={len(records)}"
        )
    return matches[0]


def _read_valid_live_generation(
    case_root: Path,
    source_signature: str,
) -> dict[str, Any] | None:
    pointer_path = case_root / "latest.json"
    if not pointer_path.is_file():
        return None
    try:
        pointer = json.loads(pointer_path.read_text(encoding="utf-8"))
        manifest_path = Path(pointer["manifest_path"]).resolve()
        if not manifest_path.is_relative_to(case_root.resolve()):
            return None
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, KeyError, TypeError, json.JSONDecodeError):
        return None
    if manifest.get("status") != "complete" or manifest.get("source_signature") != source_signature:
        return None
    export_directory = Path(manifest.get("export_directory", "")).resolve()
    if not export_directory.is_relative_to(case_root.resolve()):
        return None
    for record in manifest.get("export_files", []):
        path = Path(record.get("path", "")).resolve()
        if not path.is_relative_to(export_directory) or not path.is_file():
            return None
        if _sha256(path) != record.get("sha256"):
            return None
    manifest["manifest_path"] = str(manifest_path)
    manifest["manifest_sha256"] = _sha256(manifest_path)
    manifest["reused_immutable_generation"] = True
    return manifest


def _generate_live_case(
    case: dict[str, Any],
    live_root: Path,
    source_signature: str,
    *,
    restart: bool,
) -> dict[str, Any]:
    """Generate all four exports through the public API without touching gold data."""

    signature_root = live_root / source_signature[:20]
    case_root = signature_root / case["id"]
    if not restart and (cached := _read_valid_live_generation(case_root, source_signature)) is not None:
        return cached

    run_id = f"{datetime.now(UTC).strftime('%Y%m%dT%H%M%S.%fZ')}-{time.time_ns()}"
    run_root = case_root / "runs" / run_id
    export_root = run_root / "exports"
    export_root.mkdir(parents=True, exist_ok=False)
    started = time.perf_counter()
    captured = io.StringIO()
    manifest: dict[str, Any] = {
        "schema": SCHEMA_VERSION,
        "status": "running",
        "provenance_kind": "live_current_source",
        "source_signature": source_signature,
        "case_id": case["id"],
        "started_at": _now(),
        "run_root": str(run_root.resolve()),
        "api_calls": [],
    }
    try:
        if str(PROJECT_ROOT) not in sys.path:
            sys.path.insert(0, str(PROJECT_ROOT))
        from isocore.api import IsoDistort  # noqa: PLC0415

        selector = case["selector"]
        api = IsoDistort(language="en")
        parent_path = (WORKSPACE / "experiment_data" / case["parent"]).resolve()
        with contextlib.redirect_stdout(captured):
            api.load_structure(parent_path)
            manifest["api_calls"].append(
                {"method": "load_structure", "parent": str(parent_path), "sha256": _sha256(parent_path)}
            )
            if selector["route"] == "list_subgroups_at_kpoint":
                candidates = api.list_subgroups_at_kpoint(
                    selector["k_point"],
                    k_parameters=list(selector["k_parameters"]),
                    generate_if_missing=False,
                )
                manifest["api_calls"].append(
                    {
                        "method": "list_subgroups_at_kpoint",
                        "k_point": selector["k_point"],
                        "k_parameters": selector["k_parameters"],
                        "generate_if_missing": False,
                    }
                )
            elif selector["route"] == "list_subgroups_at":
                candidates = api.list_subgroups_at(
                    selector["k_point"],
                    selector["irrep"],
                    k_parameters=list(selector["k_parameters"]),
                    opd_symbol=selector["opd"],
                    generate_if_missing=False,
                )
                manifest["api_calls"].append(
                    {
                        "method": "list_subgroups_at",
                        "k_point": selector["k_point"],
                        "irrep": selector["irrep"],
                        "opd_symbol": selector["opd"],
                        "k_parameters": selector["k_parameters"],
                        "generate_if_missing": False,
                    }
                )
            else:
                raise ValueError(f"unknown live selector route: {selector['route']}")
            candidate = _select_live_candidate(list(candidates), selector)
            api.search_method_2(
                candidate.index,
                distortion_type=["displacive"],
                number_of_independent_modulations=int(case["nmod"] or 0),
                candidates=list(candidates),
            )
            manifest["api_calls"].append(
                {
                    "method": "search_method_2",
                    "subgroup_idx": int(candidate.index),
                    "distortion_type": ["displacive"],
                    "number_of_independent_modulations": int(case["nmod"] or 0),
                }
            )
            mode_labels = _jsonable(api._mode_labels_now())
            mode_count = len(api.mode_displacements)
            written = api.export_subgroups(
                export_root,
                formats=["cif", "isoviz", "modes", "topas"],
                subgroups=[candidate],
                compute_missing_modes=False,
                number_of_independent_modulations=int(case["nmod"] or 0),
            )
            manifest["api_calls"].append(
                {
                    "method": "export_subgroups",
                    "formats": ["cif", "isoviz", "modes", "topas"],
                    "compute_missing_modes": False,
                    "number_of_independent_modulations": int(case["nmod"] or 0),
                }
            )
        written_paths = [Path(path).resolve() for path in written]
        export_directories = {path.parent for path in written_paths}
        if len(export_directories) != 1:
            raise RuntimeError(f"one selected candidate produced {len(export_directories)} export directories")
        export_directory = next(iter(export_directories))
        expected = [export_directory / name for name in (*CORE_FILENAMES, "Complete modes details.txt")]
        missing = [str(path) for path in expected if not path.is_file()]
        if missing:
            raise RuntimeError(f"live export omitted required files: {missing}")
        export_files = [
            {"path": str(path), "sha256": _sha256(path), "bytes": path.stat().st_size}
            for path in expected
        ]
        manifest.update(
            {
                "status": "complete",
                "completed_at": _now(),
                "elapsed_seconds": time.perf_counter() - started,
                "candidate_pool_count": len(candidates),
                "selected_candidate": _candidate_record(candidate),
                "mode_count": mode_count,
                "mode_labels": mode_labels,
                "mode_label_diagnostics": _mode_label_diagnostics(mode_labels),
                "export_directory": str(export_directory),
                "export_files": export_files,
                "api_stdout_path": str((run_root / "api_stdout.log").resolve()),
                "reused_immutable_generation": False,
            }
        )
    except Exception as exc:  # noqa: BLE001 - persist a resumable scientific failure manifest
        manifest.update(
            {
                "status": "failed",
                "completed_at": _now(),
                "elapsed_seconds": time.perf_counter() - started,
                "error": f"{type(exc).__name__}: {exc}",
            }
        )
    (run_root / "api_stdout.log").write_text(captured.getvalue(), encoding="utf-8")
    manifest_path = run_root / "manifest.json"
    _atomic_json(manifest_path, manifest)
    if manifest["status"] == "complete":
        _atomic_json(
            case_root / "latest.json",
            {
                "schema": SCHEMA_VERSION,
                "source_signature": source_signature,
                "manifest_path": str(manifest_path.resolve()),
                "updated_at": _now(),
            },
        )
    manifest["manifest_path"] = str(manifest_path.resolve())
    manifest["manifest_sha256"] = _sha256(manifest_path)
    return manifest


def _load_checkpoint(path: Path, signature: str, *, restart: bool) -> dict[str, Any]:
    fresh = {
        "schema": CHECKPOINT_SCHEMA,
        "signature": signature,
        "created_at": _now(),
        "updated_at": _now(),
        "results": {},
    }
    if restart or not path.is_file():
        return fresh
    try:
        saved = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise RuntimeError(f"cannot resume unreadable checkpoint {path}; use --restart") from exc
    if saved.get("schema") != CHECKPOINT_SCHEMA:
        raise RuntimeError("checkpoint schema mismatch; use --restart")
    if saved.get("signature") != signature:
        raise RuntimeError("checkpoint signature mismatch; source or evidence changed; use --restart")
    if not isinstance(saved.get("results"), dict):
        raise RuntimeError("checkpoint results are malformed; use --restart")
    return saved


def _audit_directories(
    case: dict[str, Any],
    official: Path,
    local: Path,
    *,
    evidence_scope: str,
    provenance: dict[str, Any],
) -> dict[str, Any]:
    """Compare one immutable official directory with one local export directory."""

    expected_files = [
        *(official / name for name in CORE_FILENAMES),
        _find_modes_html(official),
        *(local / name for name in (*CORE_FILENAMES, "Complete modes details.txt")),
    ]
    missing = [str(path.resolve()) for path in expected_files if not path.is_file()]
    if missing:
        return {
            "id": case["id"],
            "status": "inconclusive",
            "coverage": case["coverage"],
            "reason": "required saved evidence is missing",
            "missing_files": missing,
            "provenance": provenance,
            "resumed_from_checkpoint": False,
        }
    try:
        official_modes = parse_official_modes_html(_find_modes_html(official))
        local_modes = parse_local_modes_text(local / "Complete modes details.txt")
        modes_result = compare_mode_datasets(
            official_modes,
            local_modes,
            compare_normfactors=True,
            compare_mode_amplitudes=True,
            require_unit_norm=True,
        )
        official_isoviz = parse_isoviz(official / "data.isoviz", official_modes.lattice)
        local_isoviz = parse_isoviz(local / "data.isoviz", local_modes.lattice)
        isoviz_result = compare_mode_datasets(
            official_isoviz,
            local_isoviz,
            compare_amplitude_bounds=True,
            require_unit_norm=True,
        )
        official_topas = parse_topas(official / "topas.str", official_modes.lattice)
        local_topas = parse_topas(local / "topas.str", local_modes.lattice)
        topas_result = compare_mode_datasets(
            official_topas,
            local_topas,
            compare_amplitude_bounds=True,
        )
        cif_result = compare_cif(official / "subgroup.cif", local / "subgroup.cif")
    except Exception as exc:  # noqa: BLE001 - preserve a scientific inconclusive record
        return {
            "id": case["id"],
            "status": "inconclusive",
            "coverage": case["coverage"],
            "reason": f"parser/comparison could not establish the claim: {type(exc).__name__}: {exc}",
            "provenance": provenance,
            "resumed_from_checkpoint": False,
        }
    exports = {
        "complete_modes": modes_result,
        "isoviz": isoviz_result,
        "topas": topas_result,
        "cif": cif_result,
    }
    failures = [name for name, result in exports.items() if result["status"] == "fail"]
    inconclusive_exports = [
        name for name, result in exports.items() if result["status"] == "inconclusive"
    ]
    status = "fail" if failures else ("inconclusive" if inconclusive_exports else "pass")
    return {
        "id": case["id"],
        "status": status,
        "coverage": case["coverage"],
        "parent": case["parent"],
        "method": case["method"],
        "folder": case["folder"],
        "nmod": case["nmod"],
        "evidence_scope": evidence_scope,
        "provenance": provenance,
        "official_directory": str(official.resolve()),
        "local_directory": str(local.resolve()),
        "failed_exports": failures,
        "inconclusive_exports": inconclusive_exports,
        "exports": exports,
        "resumed_from_checkpoint": False,
    }


def audit_case(output_root: Path, case: dict[str, Any]) -> dict[str, Any]:
    if case.get("folder") is None:
        return {
            "id": case["id"],
            "status": "inconclusive",
            "coverage": case["coverage"],
            "reason": case["inconclusive_reason"],
            "provenance": {"kind": "saved_snapshot"},
            "resumed_from_checkpoint": False,
        }
    official, local = _case_paths(output_root, case)
    return _audit_directories(
        case,
        official,
        local,
        evidence_scope=(
            "saved official/local snapshot; production source is signed for audit context "
            "but snapshot provenance does not prove live regeneration by that source"
        ),
        provenance={"kind": "saved_snapshot"},
    )


def _summary(cases: list[dict[str, Any]]) -> dict[str, Any]:
    counts = {status: sum(case["status"] == status for case in cases) for status in ("pass", "fail", "inconclusive")}
    export_counts: dict[str, dict[str, int]] = {}
    for name in ("complete_modes", "isoviz", "topas", "cif"):
        statuses = [case.get("exports", {}).get(name, {}).get("status") for case in cases]
        export_counts[name] = {
            status: sum(item == status for item in statuses) for status in ("pass", "fail", "inconclusive")
        }
    return {
        "case_count": len(cases),
        **{f"{status}_case_count": value for status, value in counts.items()},
        "export_status_counts": export_counts,
        "numeric_semantics_complete": counts["fail"] == 0 and counts["inconclusive"] == 0,
        "interpretation": (
            "A case fails if any of its four exports fails a declared numeric check. "
            "Inconclusive evidence is never counted as pass."
        ),
    }


def run_audit(
    output_root: Path = DEFAULT_OUTPUT_ROOT,
    report_path: Path = DEFAULT_REPORT,
    checkpoint_path: Path = DEFAULT_CHECKPOINT,
    *,
    restart: bool = False,
    case_ids: set[str] | None = None,
) -> dict[str, Any]:
    selected = [deepcopy(case) for case in CASE_MATRIX if case_ids is None or case["id"] in case_ids]
    unknown = sorted((case_ids or set()) - {case["id"] for case in CASE_MATRIX})
    if unknown:
        raise ValueError(f"unknown case ids: {', '.join(unknown)}")
    signature_state = _signature_state(output_root.resolve(), selected)
    checkpoint = _load_checkpoint(checkpoint_path, signature_state["signature"], restart=restart)
    checkpoint["updated_at"] = _now()
    _atomic_json(checkpoint_path, checkpoint)

    results: list[dict[str, Any]] = []
    for case in selected:
        case_id = case["id"]
        if case_id in checkpoint["results"]:
            record = deepcopy(checkpoint["results"][case_id])
            record["resumed_from_checkpoint"] = True
        else:
            record = audit_case(output_root.resolve(), case)
            checkpoint["results"][case_id] = deepcopy(record)
            checkpoint["updated_at"] = _now()
            _atomic_json(checkpoint_path, checkpoint)
        results.append(record)

    report = {
        "schema": SCHEMA_VERSION,
        "generated_at": _now(),
        "status": "complete",
        "read_only_evidence": True,
        "output_compare_modified": False,
        "scientific_method": {
            "atom_mapping": "species-preserving periodic Cartesian maximum bipartite matching",
            "displacement_conversion": "u_cart = u_frac @ direct_lattice_rows",
            "one_dimensional_equivalence": "absolute cosine/global sign",
            "degenerate_equivalence": "Cartesian column-space principal angles from SVD",
            "normalization": (
                "normfactor-scaled Complete modes and primitive-cell-filtered IsoVIZ "
                "vectors are tested for unit norm and Gram-spectrum agreement"
            ),
        },
        "tolerances": TOLERANCES,
        "signature_state": signature_state,
        "checkpoint": {
            "path": str(checkpoint_path.resolve()),
            "signature": checkpoint["signature"],
            "saved_result_count": len(checkpoint["results"]),
            "resumed_case_count": sum(bool(case["resumed_from_checkpoint"]) for case in results),
        },
        "summary": _summary(results),
        "cases": results,
        "limitations": [
            "nmod=1 has no separately archived official/local four-export evidence and is inconclusive.",
            "This audit signs saved local snapshots; a fresh live regeneration is a separate provenance claim.",
            (
                "TOPAS comparison covers saved amplitude bounds and its amplitude-to-delta "
                "Cartesian subspace; it does not run TOPAS."
            ),
            (
                "IsoVIZ comparison uses rows marked inside the primitive unit cell and does "
                "not run the graphical IsoVIZ application."
            ),
        ],
    }
    _atomic_json(report_path, report)
    checkpoint["last_summary"] = deepcopy(report["summary"])
    checkpoint["updated_at"] = _now()
    _atomic_json(checkpoint_path, checkpoint)
    return report


def _live_inconclusive_record(
    case: dict[str, Any],
    generation: dict[str, Any],
    reason: str,
) -> dict[str, Any]:
    return {
        "id": case["id"],
        "status": "inconclusive",
        "coverage": case["coverage"],
        "parent": case["parent"],
        "method": case["method"],
        "folder": case["folder"],
        "nmod": case["nmod"],
        "reason": reason,
        "provenance": {
            "kind": "live_current_source",
            "source_signature": generation.get("source_signature"),
            "generation_status": generation.get("status"),
            "generation_manifest": generation.get("manifest_path"),
            "generation_manifest_sha256": generation.get("manifest_sha256"),
        },
        "resumed_from_checkpoint": False,
    }


def run_live_audit(
    output_root: Path = DEFAULT_OUTPUT_ROOT,
    live_root: Path = DEFAULT_LIVE_ROOT,
    report_path: Path = DEFAULT_LIVE_REPORT,
    checkpoint_path: Path = DEFAULT_LIVE_CHECKPOINT,
    *,
    restart: bool = False,
    case_ids: set[str] | None = None,
) -> dict[str, Any]:
    """Generate current-source exports, then compare them with immutable official evidence."""

    selected = [
        deepcopy(case) for case in LIVE_CASE_MATRIX if case_ids is None or case["id"] in case_ids
    ]
    known = {case["id"] for case in LIVE_CASE_MATRIX}
    unknown = sorted((case_ids or set()) - known)
    if unknown:
        raise ValueError(f"unknown live case ids: {', '.join(unknown)}")
    start_signature = _live_signature_state(output_root.resolve(), selected)
    if start_signature["missing_files"]:
        raise RuntimeError(
            "live audit inputs are incomplete: " + "; ".join(start_signature["missing_files"])
        )
    checkpoint = _load_checkpoint(checkpoint_path, start_signature["signature"], restart=restart)
    checkpoint["provenance_kind"] = "live_current_source"
    checkpoint["updated_at"] = _now()
    _atomic_json(checkpoint_path, checkpoint)

    results: list[dict[str, Any]] = []
    generations: list[dict[str, Any]] = []
    for position, case in enumerate(selected, start=1):
        print(f"Live current-source generation {position}/{len(selected)}: {case['id']}")
        generation = _generate_live_case(
            case,
            live_root.resolve(),
            start_signature["source_signature"],
            restart=restart,
        )
        generations.append(generation)
        if generation.get("status") != "complete":
            record = _live_inconclusive_record(
                case,
                generation,
                f"live generation failed: {generation.get('error', 'unknown error')}",
            )
        else:
            manifest_hash = generation["manifest_sha256"]
            saved_record = checkpoint["results"].get(case["id"])
            saved_hash = (saved_record or {}).get("provenance", {}).get(
                "generation_manifest_sha256"
            )
            if saved_record is not None and saved_hash == manifest_hash:
                record = deepcopy(saved_record)
                record["resumed_from_checkpoint"] = True
            else:
                official, _saved_local = _case_paths(output_root.resolve(), case)
                provenance = {
                    "kind": "live_current_source",
                    "source_signature": start_signature["source_signature"],
                    "audit_input_signature": start_signature["signature"],
                    "generation_manifest": generation["manifest_path"],
                    "generation_manifest_sha256": manifest_hash,
                    "generation_reused": bool(generation["reused_immutable_generation"]),
                    "live_mode_count_before_export": generation["mode_count"],
                    "mode_label_diagnostics": generation["mode_label_diagnostics"],
                    "selected_candidate": generation["selected_candidate"],
                }
                record = _audit_directories(
                    case,
                    official,
                    Path(generation["export_directory"]),
                    evidence_scope=(
                        "immutable saved official export compared with files generated during "
                        "this audit through IsoDistort.search_method_2 + export_subgroups"
                    ),
                    provenance=provenance,
                )
            checkpoint["results"][case["id"]] = deepcopy(record)
            checkpoint["updated_at"] = _now()
            _atomic_json(checkpoint_path, checkpoint)
        results.append(record)

    end_signature = _live_signature_state(output_root.resolve(), selected)
    source_stable = start_signature["source_signature"] == end_signature["source_signature"]
    evidence_stable = start_signature["evidence_signature"] == end_signature["evidence_signature"]
    invocation_stable = start_signature["signature"] == end_signature["signature"]
    if not invocation_stable:
        reason = (
            "source or signed official/input evidence changed during the live audit; "
            "numerical comparisons are retained for diagnosis but cannot certify current source"
        )
        for record in results:
            record["comparison_status_before_provenance_check"] = record["status"]
            record["status"] = "inconclusive"
            record.setdefault("reason", reason)
            record["provenance_valid"] = False
            record.setdefault("inconclusive_exports", [])
        checkpoint["results"] = {record["id"]: deepcopy(record) for record in results}
        checkpoint["updated_at"] = _now()
        _atomic_json(checkpoint_path, checkpoint)
    else:
        for record in results:
            record["provenance_valid"] = True

    report = {
        "schema": SCHEMA_VERSION,
        "generated_at": _now(),
        "status": "complete" if invocation_stable else "invalidated_by_concurrent_change",
        "provenance_kind": "live_current_source",
        "read_only_official_evidence": True,
        "output_compare_modified": False,
        "live_artifact_root": str(live_root.resolve()),
        "scientific_method": {
            "atom_mapping": "species-preserving periodic Cartesian maximum bipartite matching",
            "displacement_conversion": "u_cart = u_frac @ direct_lattice_rows",
            "one_dimensional_equivalence": "absolute cosine/global sign",
            "degenerate_equivalence": "Cartesian column-space principal angles from SVD",
            "amplitude_bound_definition": (
                "A_max = 1 Angstrom / max_i(||u_i_cart(As=1)||_2); therefore the largest "
                "atomic Cartesian displacement reaches 1 Angstrom at the exported bound"
            ),
        },
        "tolerances": TOLERANCES,
        "signature_state_at_start": start_signature,
        "signature_state_at_end": end_signature,
        "provenance_stability": {
            "source_stable_during_run": source_stable,
            "official_and_parent_evidence_stable_during_run": evidence_stable,
            "complete_invocation_signature_stable": invocation_stable,
        },
        "checkpoint": {
            "path": str(checkpoint_path.resolve()),
            "signature": checkpoint["signature"],
            "saved_result_count": len(checkpoint["results"]),
            "resumed_case_count": sum(bool(case["resumed_from_checkpoint"]) for case in results),
        },
        "summary": _summary(results),
        "cases": results,
        "generations": generations,
        "limitations": [
            "The official side is an immutable downloaded snapshot; only the local side is generated live.",
            "TOPAS syntax is parsed but TOPAS itself is not executed.",
            "IsoVIZ content is parsed but the graphical IsoVIZ application is not executed.",
            "nmod=1 remains inconclusive because no independent official nmod=1 four-export archive exists.",
        ],
    }
    _atomic_json(report_path, report)
    checkpoint["last_summary"] = deepcopy(report["summary"])
    checkpoint["updated_at"] = _now()
    _atomic_json(checkpoint_path, checkpoint)
    return report


def _print_summary(report: dict[str, Any], report_path: Path, checkpoint_path: Path) -> None:
    summary = report["summary"]
    print(
        "Method1/2 numeric semantic audit: "
        f"pass={summary['pass_case_count']}, fail={summary['fail_case_count']}, "
        f"inconclusive={summary['inconclusive_case_count']}"
    )
    for case in report["cases"]:
        suffix = " (checkpoint)" if case.get("resumed_from_checkpoint") else ""
        print(f"  {case['id']}: {case['status']}{suffix}")
        for export in case.get("failed_exports", []):
            reasons = case["exports"][export].get("reasons", [])
            print(f"    {export}: {'; '.join(reasons)}")
        if case["status"] == "inconclusive":
            print(f"    {case.get('reason', 'missing evidence')}")
    print(f"Report: {report_path.resolve()}")
    print(f"Checkpoint: {checkpoint_path.resolve()}")
    if report.get("provenance_kind") == "live_current_source":
        signature = report["signature_state_at_start"]["source_signature"]
        print(f"Live source signature: {signature}")
        print(
            "Source/evidence stable during run: "
            f"{report['provenance_stability']['complete_invocation_signature_stable']}"
        )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-root", type=Path, default=DEFAULT_OUTPUT_ROOT)
    parser.add_argument("--report", type=Path, default=DEFAULT_REPORT)
    parser.add_argument("--checkpoint", type=Path, default=DEFAULT_CHECKPOINT)
    parser.add_argument("--restart", action="store_true", help="replace a compatible checkpoint")
    parser.add_argument("--case", action="append", dest="cases", help="run only this case id; repeatable")
    parser.add_argument(
        "--live-current-source",
        action="store_true",
        help="generate three exports from current source and compare them with official evidence",
    )
    parser.add_argument("--live-root", type=Path, default=DEFAULT_LIVE_ROOT)
    parser.add_argument("--live-report", type=Path, default=DEFAULT_LIVE_REPORT)
    parser.add_argument("--live-checkpoint", type=Path, default=DEFAULT_LIVE_CHECKPOINT)
    parser.add_argument(
        "--live-restart",
        action="store_true",
        help="force a new immutable live generation attempt and replace the live checkpoint",
    )
    args = parser.parse_args(argv)
    try:
        if args.live_current_source:
            report_path = args.live_report.expanduser().resolve()
            checkpoint_path = args.live_checkpoint.expanduser().resolve()
            report = run_live_audit(
                args.output_root.expanduser().resolve(),
                args.live_root.expanduser().resolve(),
                report_path,
                checkpoint_path,
                restart=args.restart or args.live_restart,
                case_ids=set(args.cases) if args.cases else None,
            )
        else:
            report_path = args.report.expanduser().resolve()
            checkpoint_path = args.checkpoint.expanduser().resolve()
            report = run_audit(
                args.output_root.expanduser().resolve(),
                report_path,
                checkpoint_path,
                restart=args.restart,
                case_ids=set(args.cases) if args.cases else None,
            )
    except Exception as exc:  # noqa: BLE001 - CLI must preserve a clear failed invocation
        print(f"ERROR: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 2
    _print_summary(report, report_path, checkpoint_path)
    return 1 if report["summary"]["fail_case_count"] else 0


if __name__ == "__main__":
    raise SystemExit(main())
