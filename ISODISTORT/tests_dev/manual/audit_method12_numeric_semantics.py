def _now() -> str:
    return datetime.now(UTC).isoformat()


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _atomic_json(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f"{path.name}.tmp")
    temporary.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    os.replace(temporary, path)


def _html_pre_text(path: Path) -> str:
    raw = path.read_text(encoding="utf-8-sig", errors="replace")
    match = re.search(r"<pre[^>]*>(.*?)</pre>", raw, flags=re.IGNORECASE | re.DOTALL)
    if not match:
        raise ValueError(f"no <pre> payload in official modes HTML: {path}")
    body = re.sub(r"<br\s*/?>", "\n", match.group(1), flags=re.IGNORECASE)
    body = re.sub(r"<[^>]+>", "", body)
    return html_module.unescape(body).replace("\r\n", "\n")


def _species_from_token(token: str) -> str:
    match = re.match(r"([A-Za-z]+)", token)
    if not match:
        raise ValueError(f"cannot infer chemical species from atom token {token!r}")
    # Official pages sometimes uppercase complete atom labels (ND1, NI1), not
    # just the first element-symbol letter.  Chemical symbols are normalized
    # independently of that presentation convention.
    return match.group(1).capitalize()


def _lattice_from_parameters(
    a: float,
    b: float,
    c: float,
    alpha: float,
    beta: float,
    gamma: float,
) -> np.ndarray:
    ar, br, gr = map(math.radians, (alpha, beta, gamma))
    avec = np.array([a, 0.0, 0.0], dtype=float)
    bvec = np.array([b * math.cos(gr), b * math.sin(gr), 0.0], dtype=float)
    cx = c * math.cos(br)
    cy = c * (math.cos(ar) - math.cos(br) * math.cos(gr)) / max(math.sin(gr), 1.0e-15)
    cz2 = max(c * c - cx * cx - cy * cy, 0.0)
    cvec = np.array([cx, cy, math.sqrt(cz2)], dtype=float)
    return np.vstack((avec, bvec, cvec))


def _parse_lattice(text: str) -> np.ndarray:
    pattern = (
        rf"a\s*=\s*({_FLOAT})\s*,?\s*b\s*=\s*({_FLOAT})\s*,?\s*"
        rf"c\s*=\s*({_FLOAT})\s*,?\s*alpha\s*=\s*({_FLOAT})\s*,?\s*"
        rf"beta\s*=\s*({_FLOAT})\s*,?\s*gamma\s*=\s*({_FLOAT})"
    )
    matches = list(re.finditer(pattern, text, flags=re.IGNORECASE))
    if matches:
        # Official pages print the parent lattice first and the undistorted
        # supercell afterwards (sometimes once more in a Cartesian section).
        # The final tuple is consequently the displacement-vector basis.
        return _lattice_from_parameters(*(float(value) for value in matches[-1].groups()))
    raise ValueError("lattice parameters were not found")


def _canonical_label(label: str, *, compact: bool = False) -> str:
    value = re.sub(r"\s+", "", label.strip())
    # OPD annotations identify the route/subgroup, not a separate atomic mode
    # vector.  Official and local snapshots may print equivalent restricted vs
    # full OPD notation, e.g. GM5-(a,0) vs GM5-(a,b).
    value = re.sub(r"(?<=[A-Za-z0-9+\-])\([^)]*\)(?=\[)", "", value)
    if compact:
        # Official IsoVIZ omits integer-coordinate prefixes on named special-k
        # labels, whereas local exports may retain them.  Fractional parameter-k
        # coordinates (e.g. [0,0,1/6]LD1) remain scientifically significant.
        value = re.sub(
            r"^\[[^]]+\](?=(?:GM|X|M|Z|R|A)\d)",
            "",
            value,
            flags=re.IGNORECASE,
        )
    return value.casefold()


def _family_key(label: str) -> str:
    value = re.sub(r"\([A-Za-z0-9_]+\)$", "", label)
    # Repeated copies of the same site irrep (A1_1/A1_2, etc.) have no
    # canonical basis: an orthogonal rotation may mix them.  Compare their
    # joint fixed subspace instead of assigning physical meaning to suffixes.
    return re.sub(r"_\d+$", "", value)


def _labels_by_family(labels: Iterable[str]) -> dict[str, list[str]]:
    grouped: dict[str, list[str]] = {}
    for label in sorted(labels):
        grouped.setdefault(_family_key(label), []).append(label)
    return grouped


def _unique_mode_label(label: str, modes: dict[str, Mode]) -> str:
    """Preserve duplicate exported columns instead of silently overwriting them."""

    if label not in modes:
        return label
    duplicate = 2
    while f"{label}#duplicate{duplicate}" in modes:
        duplicate += 1
    return f"{label}#duplicate{duplicate}"


def _without_parent_space_group(label: str) -> str:
    start = label.find("[")
    return label[start:] if start >= 0 else label


def _primitive_size_ratio(text: str) -> int | None:
    match = re.search(r"\bs\s*=\s*(\d+)\s*[, ]", text)
    if not match:
        return None
    value = int(match.group(1))
    return value if value > 0 else None


def _strip_leading_k(label: str) -> str:
    return re.sub(r"^\[[^]]+\](?=[a-z])", "", label, flags=re.IGNORECASE)


def _compatible_compact_keys(
    official: ModeDataset,
    local: ModeDataset,
) -> tuple[ModeDataset, ModeDataset]:
    """Reconcile optional compact-label k prefixes only when unambiguous.

    IsoVIZ may omit the explicit k coordinate before a named irrep.  Removing
    it globally would collapse distinct LD harmonics, so an alias is accepted
    only when exactly one unmatched mode on each side has the same stripped
    key.
    """

    left_keys = set(official.modes)
    right_keys = set(local.modes)
    left_unmatched = left_keys - right_keys
    right_unmatched = right_keys - left_keys
    left_groups: dict[str, list[str]] = {}
    right_groups: dict[str, list[str]] = {}
    for key in left_unmatched:
        left_groups.setdefault(_strip_leading_k(key), []).append(key)
    for key in right_unmatched:
        right_groups.setdefault(_strip_leading_k(key), []).append(key)
    aliases_left: dict[str, str] = {}
    aliases_right: dict[str, str] = {}
    for stripped in set(left_groups) & set(right_groups):
        if len(left_groups[stripped]) == len(right_groups[stripped]) == 1:
            aliases_left[left_groups[stripped][0]] = stripped
            aliases_right[right_groups[stripped][0]] = stripped

    def remap(dataset: ModeDataset, aliases: dict[str, str]) -> ModeDataset:
        modes = {}
        for key, mode in dataset.modes.items():
            new_key = aliases.get(key, key)
            if new_key in modes:
                raise ValueError(f"ambiguous compact-label alias {new_key!r}")
            modes[new_key] = Mode(
                new_key,
                mode.vectors,
                normfactor=mode.normfactor,
                amplitude_bound=mode.amplitude_bound,
                amplitude_supercell=mode.amplitude_supercell,
                amplitude_parent=mode.amplitude_parent,
                dmax_angstrom=mode.dmax_angstrom,
            )
        return ModeDataset(dataset.atoms, dataset.lattice, modes, dataset.metadata)

    return remap(official, aliases_left), remap(local, aliases_right)


def parse_official_modes_html(path: Path) -> ModeDataset:
    text = _html_pre_text(path)
    lattice = _parse_lattice(text)
    section = text.split("Displacive mode definitions", 1)
    if len(section) != 2:
        raise ValueError("official HTML contains no displacive mode definitions")
    displacement_text = section[1].split("Parent-cell strain mode definitions", 1)[0]

    mode_rows: dict[str, list[tuple[Atom, np.ndarray]]] = {}
    normfactors: dict[str, float] = {}
    current_label: str | None = None
    current_species: str | None = None
    for line in displacement_text.splitlines():
        header = _MODE_HEADER_RE.match(line.strip())
        if header and ":dsp]" in header.group("label"):
            current_label = _unique_mode_label(
                _canonical_label(header.group("label")),
                mode_rows,
            )
            normfactors[current_label] = float(header.group("norm"))
            mode_rows[current_label] = []
            current_species = None
            continue
        if current_label is None:
            continue
        row = _OFFICIAL_ROW_RE.match(line)
        if not row:
            continue
        token = row.group("token") or ""
        if token:
            current_species = _species_from_token(token)
        if current_species is None:
            raise ValueError(f"unlabelled official atom row before a labelled row: {line!r}")
        frac = np.array([float(row.group(axis)) for axis in ("x", "y", "z")])
        vector = np.array([float(row.group(axis)) for axis in ("dx", "dy", "dz")])
        mode_rows[current_label].append((Atom(current_species, frac, token), vector))

    atoms = _unique_atoms(atom for rows in mode_rows.values() for atom, _vector in rows)
    modes: dict[str, Mode] = {}
    for label, rows in mode_rows.items():
        vectors = _rows_on_atoms(rows, atoms, lattice)
        modes[label] = Mode(label, vectors, normfactor=normfactors[label])
    if not modes:
        raise ValueError("no displacive modes parsed from official HTML")

    amplitude_section = text.split("Displacive mode amplitudes", 1)
    parsed_amplitudes = 0
    unmatched_amplitudes: list[str] = []
    if len(amplitude_section) == 2:
        amplitude_text = amplitude_section[1].split("Parent-cell strain mode definitions", 1)[0]
        amplitude_re = re.compile(
            rf"^\s*(?P<label>\S.*?:dsp]\S*)\s+(?P<as>{_FLOAT})\s+"
            rf"(?P<ap>{_FLOAT})\s+(?P<dmax>{_FLOAT})\s*$"
        )
        aliases: dict[str, list[str]] = {}
        for label in modes:
            aliases.setdefault(_without_parent_space_group(label), []).append(label)
        for line in amplitude_text.splitlines():
            match = amplitude_re.match(line)
            if not match:
                continue
            short_label = _canonical_label(match.group("label"))
            candidates = aliases.get(short_label, [])
            if len(candidates) != 1:
                unmatched_amplitudes.append(short_label)
                continue
            mode = modes[candidates[0]]
            mode.amplitude_supercell = float(match.group("as"))
            mode.amplitude_parent = float(match.group("ap"))
            mode.dmax_angstrom = float(match.group("dmax"))
            parsed_amplitudes += 1
    return ModeDataset(
        atoms,
        lattice,
        modes,
        {
            "path": str(path.resolve()),
            "format": "official-html",
            "primitive_size_ratio": _primitive_size_ratio(text),
            "parsed_amplitude_rows": parsed_amplitudes,
            "unmatched_amplitude_labels": unmatched_amplitudes,
        },
    )


def parse_local_modes_text(path: Path) -> ModeDataset:
    text = path.read_text(encoding="utf-8-sig", errors="replace")
    lattice = _parse_lattice(text)
    atoms_by_index: dict[int, Atom] = {}
    atom_re = re.compile(
        rf"^\s*(?P<idx>\d+)\s+(?P<species>[A-Z][a-z]?)\s+"
        rf"(?P<x>{_FLOAT})\s+(?P<y>{_FLOAT})\s+(?P<z>{_FLOAT})\s*$"
    )
    before_modes = text.split("Mode definitions", 1)[0]
    for line in before_modes.splitlines():
        match = atom_re.match(line)
        if match:
            idx = int(match.group("idx"))
            atoms_by_index[idx] = Atom(
                match.group("species"),
                np.array([float(match.group(axis)) for axis in ("x", "y", "z")]),
                str(idx),
            )
    if not atoms_by_index:
        raise ValueError("local modes text contains no superstructure atom table")
    expected = list(range(1, max(atoms_by_index) + 1))
    if sorted(atoms_by_index) != expected:
        raise ValueError("local modes atom indices are not contiguous")
    atoms = [atoms_by_index[idx] for idx in expected]

    modes: dict[str, Mode] = {}
    internal_to_label: dict[str, str] = {}
    lines = text.splitlines()
    current: Mode | None = None
    vector_re = re.compile(
        rf"^\s*atom\s+(?P<idx>\d+)\s+(?P<species>[A-Z][a-z]?)\s+"
        rf"\(\s*(?P<dx>{_FLOAT})\s*,\s*(?P<dy>{_FLOAT})\s*,\s*(?P<dz>{_FLOAT})\s*\)"
    )
    for line in lines:
        if line.startswith("Mode ") and ":dsp]" in line:
            pieces = line.split(None, 2)
            if len(pieces) != 3:
                raise ValueError(f"malformed local mode header: {line!r}")
            internal = pieces[1]
            label = _unique_mode_label(_canonical_label(pieces[2]), modes)
            current = Mode(label, np.zeros((len(atoms), 3), dtype=float))
            modes[label] = current
            internal_to_label[internal] = label
            continue
        if current is None:
            continue
        norm = re.match(rf"^\s*normfactor\s*=\s*(?P<value>{_FLOAT})", line)
        if norm:
            current.normfactor = float(norm.group("value"))
            continue
        vector = vector_re.match(line)
        if vector:
            idx = int(vector.group("idx"))
            if atoms[idx - 1].species != vector.group("species"):
                raise ValueError(f"mode atom species disagrees with atom table at index {idx}")
            current.vectors[idx - 1] = [float(vector.group(axis)) for axis in ("dx", "dy", "dz")]
    if not modes or any(mode.normfactor is None for mode in modes.values()):
        raise ValueError("local modes text has missing mode definitions or normfactors")
    amplitude_re = re.compile(
        rf"^\s*(?P<internal>\S+)\s+As=\s*(?P<as>{_FLOAT})\s+"
        rf"Ap=\s*(?P<ap>{_FLOAT})\s+dmax=\s*(?P<dmax>{_FLOAT})\s+Angstrom\s*$"
    )
    parsed_amplitudes = 0
    unmatched_amplitudes: list[str] = []
    for line in lines:
        match = amplitude_re.match(line)
        if not match:
            continue
        label = internal_to_label.get(match.group("internal"))
        if label is None:
            unmatched_amplitudes.append(match.group("internal"))
            continue
        mode = modes[label]
        mode.amplitude_supercell = float(match.group("as"))
        mode.amplitude_parent = float(match.group("ap"))
        mode.dmax_angstrom = float(match.group("dmax"))
        parsed_amplitudes += 1
    return ModeDataset(
        atoms,
        lattice,
        modes,
        {
            "path": str(path.resolve()),
            "format": "local-text",
            "primitive_size_ratio": _primitive_size_ratio(text),
            "parsed_amplitude_rows": parsed_amplitudes,
            "unmatched_amplitude_labels": unmatched_amplitudes,
        },
    )


def _unique_atoms(atoms: Iterable[Atom], tolerance: float = 1.0e-7) -> list[Atom]:
    result: list[Atom] = []
    for atom in atoms:
        duplicate = False
        for existing in result:
            if atom.species != existing.species:
                continue
            delta = atom.frac - existing.frac
            delta -= np.rint(delta)
            if float(np.max(np.abs(delta))) <= tolerance:
                duplicate = True
                break
        if not duplicate:
            result.append(Atom(atom.species, np.mod(atom.frac, 1.0), atom.token))
    return result


def _fractional_cart_distance(left: np.ndarray, right: np.ndarray, lattice: np.ndarray) -> float:
    delta = right - left
    delta -= np.rint(delta)
    return float(np.linalg.norm(delta @ lattice))


def _atom_bijection(
    left: list[Atom],
    right: list[Atom],
    lattice: np.ndarray,
    tolerance: float,
) -> tuple[list[int], float]:
    if len(left) != len(right):
        raise ValueError(f"atom counts differ: {len(left)} != {len(right)}")
    adjacency: list[list[tuple[int, float]]] = []
    for atom in left:
        candidates = []
        for index, other in enumerate(right):
            if atom.species != other.species:
                continue
            distance = _fractional_cart_distance(atom.frac, other.frac, lattice)
            if distance <= tolerance:
                candidates.append((index, distance))
        candidates.sort(key=lambda item: (item[1], item[0]))
        if not candidates:
            raise ValueError(
                f"no periodic same-species match for {atom.species} at {atom.frac.tolist()}"
            )
        adjacency.append(candidates)

    match_right = [-1] * len(right)

    def augment(left_index: int, visited: set[int]) -> bool:
        for right_index, _distance in adjacency[left_index]:
            if right_index in visited:
                continue
            visited.add(right_index)
            if match_right[right_index] < 0 or augment(match_right[right_index], visited):
                match_right[right_index] = left_index
                return True
        return False

    order = sorted(range(len(left)), key=lambda index: len(adjacency[index]))
    for left_index in order:
        if not augment(left_index, set()):
            raise ValueError("same-species periodic atom graph has no perfect matching")
    mapping = [-1] * len(left)
    for right_index, left_index in enumerate(match_right):
        mapping[left_index] = right_index
    distances = [
        _fractional_cart_distance(left[index].frac, right[mapping[index]].frac, lattice)
        for index in range(len(left))
    ]
    return mapping, max(distances, default=0.0)


def _atom_bijection_with_origin_shift(
    left: list[Atom],
    right: list[Atom],
    lattice: np.ndarray,
    tolerance: float,
) -> tuple[list[int], float, list[float]]:
    """Match periodic atoms after one species-preserving global origin shift."""

    try:
        mapping, error = _atom_bijection(left, right, lattice, tolerance)
        return mapping, error, [0.0, 0.0, 0.0]
    except ValueError as direct_error:
        direct_error_message = str(direct_error)
        if not left or len(left) != len(right):
            raise ValueError(direct_error_message) from direct_error
    species_counts = {
        species: sum(atom.species == species for atom in left)
        for species in {atom.species for atom in left}
    }
    anchor_species = min(species_counts, key=lambda species: (species_counts[species], species))
    anchor = next(atom for atom in left if atom.species == anchor_species)
    shifts = []
    seen = set()
    for other in right:
        if other.species != anchor_species:
            continue
        shift = np.asarray(other.frac - anchor.frac, dtype=float)
        shift -= np.rint(shift)
        key = tuple(round(float(value), 10) for value in shift)
        if key not in seen:
            seen.add(key)
            shifts.append(shift)
    best: tuple[list[int], float, np.ndarray] | None = None
    for shift in shifts:
        shifted = [Atom(atom.species, atom.frac + shift, atom.token) for atom in left]
        try:
            mapping, error = _atom_bijection(shifted, right, lattice, tolerance)
        except ValueError:
            continue
        if best is None or (error, tuple(shift)) < (best[1], tuple(best[2])):
            best = (mapping, error, shift)
    if best is None:
        raise ValueError(direct_error_message)
    mapping, error, shift = best
    return mapping, error, [float(value) for value in shift]


def _rows_on_atoms(
    rows: Iterable[tuple[Atom, np.ndarray]],
    atoms: list[Atom],
    lattice: np.ndarray,
) -> np.ndarray:
    vectors = np.zeros((len(atoms), 3), dtype=float)
    used: set[int] = set()
    tolerance = float(TOLERANCES["atom_cartesian_distance_angstrom"])
    for atom, vector in rows:
        choices = [
            (index, _fractional_cart_distance(atom.frac, reference.frac, lattice))
            for index, reference in enumerate(atoms)
            if atom.species == reference.species and index not in used
        ]
        choices = [choice for choice in choices if choice[1] <= tolerance]
        if not choices:
            raise ValueError(f"cannot place mode row for {atom.token or atom.species}")
        index = min(choices, key=lambda item: item[1])[0]
        used.add(index)
        vectors[index] = vector
    return vectors


def _section(lines: list[str], tag: str) -> list[str]:
    try:
        start = next(index for index, line in enumerate(lines) if line.strip() == tag) + 1
    except StopIteration as exc:
        raise ValueError(f"missing IsoVIZ section {tag}") from exc
    result = []
    for line in lines[start:]:
        stripped = line.strip()
        if stripped.startswith("!") or stripped.startswith("#"):
            break
        if stripped:
            result.append(line)
    return result


def parse_isoviz(path: Path, lattice: np.ndarray) -> ModeDataset:
    lines = path.read_text(encoding="utf-8-sig", errors="replace").splitlines()
    types: dict[int, tuple[str, str]] = {}
    for line in _section(lines, "!atomtypelist"):
        parts = line.split()
        if len(parts) >= 3 and parts[0].isdigit():
            types[int(parts[0])] = (parts[1], parts[2])
    coord_rows: list[tuple[int, Atom]] = []
    coord_re = re.compile(
        rf"^\s*(?P<parent>\d+)\s+(?P<type>\d+)\s+(?P<sub>\d+)\s+"
        rf"(?P<x>{_FLOAT})\s+(?P<y>{_FLOAT})\s+(?P<z>{_FLOAT})\s*$"
    )
    for line in _section(lines, "!atomcoordlist"):
        match = coord_re.match(line)
        if not match:
            continue
        parent = int(match.group("parent"))
        if parent not in types:
            raise ValueError(f"IsoVIZ coordinate references unknown atom type {parent}")
        token, species = types[parent]
        coord_rows.append(
            (
                parent,
                Atom(
                    species,
                    np.array([float(match.group(axis)) for axis in ("x", "y", "z")]),
                    f"{token}:{match.group('type')}:{match.group('sub')}",
                ),
            )
        )
    flags = [int(line.strip()) for line in _section(lines, "!atomsinunitcell") if line.strip() in {"0", "1"}]
    if len(flags) != len(coord_rows):
        raise ValueError(f"IsoVIZ primitive flags {len(flags)} != coordinate rows {len(coord_rows)}")
    primitive_rows = [row for row, flag in zip(coord_rows, flags, strict=True) if flag]
    atoms = [atom for _parent, atom in primitive_rows]

    start = next(index for index, line in enumerate(lines) if line.strip() == "!displacivemodelist") + 1
    header_re = re.compile(
        rf"^\s*(?P<parent>\d+)\s+(?P<num>\d+)\s+(?P<amp>{_FLOAT})\s+"
        rf"(?P<maxamp>{_FLOAT})\s+(?P<irnum>\d+)\s+(?P<label>\S.*)\s*$"
    )
    vector_re = re.compile(rf"^\s*({_FLOAT})\s+({_FLOAT})\s+({_FLOAT})\s*$")
    modes: dict[str, Mode] = {}
    index = start
    by_parent_all: dict[int, list[tuple[int, Atom]]] = {}
    for row_index, (parent, atom) in enumerate(coord_rows):
        by_parent_all.setdefault(parent, []).append((row_index, atom))
    primitive_index: dict[int, int] = {}
    for row_index, flag in enumerate(flags):
        if flag:
            primitive_index[row_index] = len(primitive_index)
    while index < len(lines):
        stripped = lines[index].strip()
        if stripped.startswith("!") or (stripped.startswith("#") and modes):
            break
        header = header_re.match(lines[index])
        if not header:
            index += 1
            continue
        parent = int(header.group("parent"))
        coordinate_rows = by_parent_all.get(parent, [])
        values: list[np.ndarray] = []
        for offset in range(len(coordinate_rows)):
            if index + 1 + offset >= len(lines):
                raise ValueError("truncated IsoVIZ displacive mode vector")
            vector = vector_re.match(lines[index + 1 + offset])
            if not vector:
                raise ValueError(f"malformed IsoVIZ vector row: {lines[index + 1 + offset]!r}")
            values.append(np.array([float(item) for item in vector.groups()]))
        all_vectors = np.zeros((len(atoms), 3), dtype=float)
        for (row_index, _atom), vector in zip(coordinate_rows, values, strict=True):
            if row_index in primitive_index:
                all_vectors[primitive_index[row_index]] = vector
        label = _unique_mode_label(
            _canonical_label(header.group("label"), compact=True),
            modes,
        )
        modes[label] = Mode(
            label,
            all_vectors,
            amplitude_bound=float(header.group("maxamp")),
        )
        index += len(coordinate_rows) + 1
    if not modes:
        raise ValueError("no IsoVIZ displacive modes parsed")
    return ModeDataset(atoms, lattice, modes, {"path": str(path.resolve()), "format": "isoviz"})


def parse_topas(path: Path, lattice: np.ndarray) -> ModeDataset:
    lines = path.read_text(encoding="utf-8-sig", errors="replace").splitlines()
    param_re = re.compile(
        rf"^\s*prm\s+!(?P<param>a\d+)\s+(?P<amp>{_FLOAT})\s+min\s+"
        rf"(?P<minimum>{_FLOAT})\s+max\s+(?P<maximum>{_FLOAT})\s+'(?P<label>.+?)\s*$"
    )
    params: dict[str, tuple[str, float]] = {}
    for line in lines:
        match = param_re.match(line)
        if match:
            label = _canonical_label(match.group("label"))
            bound = max(abs(float(match.group("minimum"))), abs(float(match.group("maximum"))))
            params[match.group("param")] = (label, bound)
    if not params:
        raise ValueError("TOPAS contains no displacive amplitude parameters")

    coordinate_re = re.compile(
        rf"^\s*prm\s+!?(?P<atom>[A-Za-z][\w.+-]*)_(?P<axis>[xyz])\s*=.*;:\s*"
        rf"(?P<value>{_FLOAT})\s*$"
    )
    coordinates: dict[str, dict[str, float]] = {}
    for line in lines:
        match = coordinate_re.match(line)
        if match:
            coordinates.setdefault(match.group("atom"), {})[match.group("axis")] = float(match.group("value"))
    def atom_sort_key(token: str) -> tuple[str, int, str]:
        suffix = re.search(r"(\d+)$", token)
        return re.sub(r"\d+$", "", token), int(suffix.group(1)) if suffix else 0, token

    atom_tokens = sorted(
        (token for token, xyz in coordinates.items() if set(xyz) == {"x", "y", "z"}),
        key=atom_sort_key,
    )
    atoms = [
        Atom(
            _species_from_token(token),
            np.array([coordinates[token][axis] for axis in ("x", "y", "z")]),
            token,
        )
        for token in atom_tokens
    ]
    if not atoms:
        raise ValueError("TOPAS contains no complete atomic coordinate triplets")
    atom_index = {atom.token: index for index, atom in enumerate(atoms)}

    matrices = {param: np.zeros((len(atoms), 3), dtype=float) for param in params}
    transform_re = re.compile(
        r"^\s*prm\s+!?(?P<atom>[A-Za-z][\w.+-]*)_d(?P<axis>[xyz])\s*=\s*"
        r"(?P<expr>.*?)\s*;:"
    )
    term_re = re.compile(rf"(?P<sign>[+-])\s*(?P<coef>{_FLOAT})\s*\*\s*(?P<param>a\d+)")
    axis_index = {"x": 0, "y": 1, "z": 2}
    for line in lines:
        transform = transform_re.match(line)
        if not transform or transform.group("atom") not in atom_index:
            continue
        row = atom_index[transform.group("atom")]
        column = axis_index[transform.group("axis")]
        for term in term_re.finditer(transform.group("expr")):
            param = term.group("param")
            if param not in matrices:
                continue
            sign = -1.0 if term.group("sign") == "-" else 1.0
            matrices[param][row, column] += sign * float(term.group("coef"))
    modes: dict[str, Mode] = {}
    for param, (raw_label, bound) in params.items():
        label = _unique_mode_label(raw_label, modes)
        modes[label] = Mode(label, matrices[param], amplitude_bound=bound)
    return ModeDataset(atoms, lattice, modes, {"path": str(path.resolve()), "format": "topas"})


def _lattice_lengths_angles(lattice: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    lengths = np.linalg.norm(lattice, axis=1)
    angles = []
    for left, right in ((1, 2), (0, 2), (0, 1)):
        cosine = np.dot(lattice[left], lattice[right]) / (lengths[left] * lengths[right])
        angles.append(math.degrees(math.acos(float(np.clip(cosine, -1.0, 1.0)))))
    return lengths, np.array(angles)


def compare_cif(official: Path, local: Path) -> dict[str, Any]:
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", UserWarning)
        left = CifParser(str(official)).parse_structures(primitive=False)[0]
        right = CifParser(str(local)).parse_structures(primitive=False)[0]
    left_atoms = [Atom(str(site.specie), np.asarray(site.frac_coords, dtype=float)) for site in left]
    right_atoms = [Atom(str(site.specie), np.asarray(site.frac_coords, dtype=float)) for site in right]
    left_lengths, left_angles = _lattice_lengths_angles(left.lattice.matrix)
    right_lengths, right_angles = _lattice_lengths_angles(right.lattice.matrix)
    length_error = float(np.max(np.abs(left_lengths - right_lengths)))
    angle_error = float(np.max(np.abs(left_angles - right_angles)))
    try:
        _mapping, atom_error = _atom_bijection(
            left_atoms,
            right_atoms,
            left.lattice.matrix,
            float(TOLERANCES["atom_cartesian_distance_angstrom"]),
        )
        mapping_error = None
    except ValueError as exc:
        atom_error = None
        mapping_error = str(exc)
    passed = (
        mapping_error is None
        and length_error <= float(TOLERANCES["lattice_length_angstrom"])
        and angle_error <= float(TOLERANCES["lattice_angle_degrees"])
    )
    return {
        "status": "pass" if passed else "fail",
        "official_atom_count": len(left_atoms),
        "local_atom_count": len(right_atoms),
        "max_lattice_length_error_angstrom": length_error,
        "max_lattice_angle_error_degrees": angle_error,
        "max_species_periodic_mapping_error_angstrom": atom_error,
        "mapping_error": mapping_error,
    }


def _cartesian_matrix(dataset: ModeDataset, labels: list[str], reorder: list[int] | None = None) -> np.ndarray:
    columns = []
    for label in labels:
        mode = dataset.modes[label]
        vectors = mode.vectors if reorder is None else mode.vectors[reorder]
        cartesian = vectors @ dataset.lattice
        if mode.normfactor is not None:
            cartesian = cartesian * mode.normfactor
        columns.append(cartesian.reshape(-1))
    return np.column_stack(columns) if columns else np.empty((len(dataset.atoms) * 3, 0))


def _active_dataset(dataset: ModeDataset) -> ModeDataset:
    """Remove atoms that are identically zero in every displacive mode.

    Official Complete-modes pages list only atoms on active parent orbits in
    their mode blocks, while the local text begins from the whole supercell.
    Zero rows carry no mode-space information, so retaining them would make an
    otherwise valid species/position bijection depend on presentation scope.
    """

    if not dataset.modes:
        return dataset
    activity = np.zeros(len(dataset.atoms), dtype=bool)
    for mode in dataset.modes.values():
        activity |= np.linalg.norm(mode.vectors, axis=1) > 1.0e-14
    indices = np.flatnonzero(activity)
    atoms = [dataset.atoms[int(index)] for index in indices]
    modes = {
        label: Mode(
            label,
            mode.vectors[indices],
            normfactor=mode.normfactor,
            amplitude_bound=mode.amplitude_bound,
            amplitude_supercell=mode.amplitude_supercell,
            amplitude_parent=mode.amplitude_parent,
            dmax_angstrom=mode.dmax_angstrom,
        )
        for label, mode in dataset.modes.items()
    }
    return ModeDataset(atoms, dataset.lattice, modes, {**dataset.metadata, "active_atom_filter": True})


def _amplitude_formula_audit(dataset: ModeDataset) -> dict[str, Any]:
    """Check Ap and dmax from the exported As, normfactor, s, and mode vector."""

    primitive_size = dataset.metadata.get("primitive_size_ratio")
    complete = [
        (label, mode)
        for label, mode in dataset.modes.items()
        if mode.amplitude_supercell is not None
        and mode.amplitude_parent is not None
        and mode.dmax_angstrom is not None
    ]
    missing = sorted(set(dataset.modes) - {label for label, _mode in complete})
    if primitive_size is None:
        return {
            "status": "inconclusive",
            "reason": "subgroup primitive size ratio s was not parsed",
            "mode_count": len(dataset.modes),
            "complete_triplet_count": len(complete),
            "missing_triplet_labels": missing,
        }
    mismatches = []
    nonzero = 0
    max_ap_error = 0.0
    max_dmax_error = 0.0
    for label, mode in complete:
        assert mode.amplitude_supercell is not None
        assert mode.amplitude_parent is not None
        assert mode.dmax_angstrom is not None
        if mode.normfactor is None:
            missing.append(label)
            continue
        amplitude = float(mode.amplitude_supercell)
        nonzero += int(abs(amplitude) > float(TOLERANCES["mode_amplitude_absolute"]))
        expected_ap = amplitude / math.sqrt(float(primitive_size))
        cartesian = mode.vectors @ dataset.lattice
        maximum_cartesian = float(np.max(np.linalg.norm(cartesian, axis=1), initial=0.0))
        expected_dmax = abs(amplitude) * float(mode.normfactor) * maximum_cartesian
        ap_error = abs(float(mode.amplitude_parent) - expected_ap)
        dmax_error = abs(float(mode.dmax_angstrom) - expected_dmax)
        max_ap_error = max(max_ap_error, ap_error)
        max_dmax_error = max(max_dmax_error, dmax_error)
        if (
            ap_error > float(TOLERANCES["mode_amplitude_formula_absolute"])
            or dmax_error > float(TOLERANCES["mode_dmax_angstrom"])
        ):
            mismatches.append(
                {
                    "label": label,
                    "reported": {
                        "As": amplitude,
                        "Ap": mode.amplitude_parent,
                        "dmax_angstrom": mode.dmax_angstrom,
                    },
                    "expected": {"Ap": expected_ap, "dmax_angstrom": expected_dmax},
                    "errors": {"Ap": ap_error, "dmax_angstrom": dmax_error},
                }
            )
    if mismatches:
        status = "fail"
    elif missing:
        status = "inconclusive"
    else:
        status = "pass"
    return {
        "status": status,
        "formula": {
            "Ap": "As / sqrt(s)",
            "dmax": "abs(As) * normfactor * max_i(||u_i_fractional @ lattice||_2)",
        },
        "primitive_size_ratio_s": primitive_size,
        "mode_count": len(dataset.modes),
        "complete_triplet_count": len(complete),
        "missing_triplet_labels": sorted(set(missing)),
        "nonzero_amplitude_count": nonzero,
        "nonzero_formula_coverage": (
            {"status": "pass", "count": nonzero}
            if nonzero
            else {
                "status": "inconclusive",
                "count": 0,
                "reason": "saved official/default live export has As=0 for every mode",
            }
        ),
        "max_Ap_formula_abs_error": max_ap_error,
        "max_dmax_formula_abs_error_angstrom": max_dmax_error,
        "mismatches": mismatches[:20],
    }


def _orthonormal_basis(matrix: np.ndarray) -> tuple[np.ndarray, int]:
    if not matrix.size:
        return matrix, 0
    u, singular, _vt = np.linalg.svd(matrix, full_matrices=False)
    if not len(singular) or singular[0] == 0.0:
        return u[:, :0], 0
    rank = int(np.sum(singular > singular[0] * float(TOLERANCES["basis_rank_relative"])))
    return u[:, :rank], rank


def compare_mode_datasets(
    official: ModeDataset,
    local: ModeDataset,
    *,
    compare_normfactors: bool = False,
    compare_amplitude_bounds: bool = False,
    compare_mode_amplitudes: bool = False,
    require_unit_norm: bool = False,
) -> dict[str, Any]:
    official = _active_dataset(official)
    local = _active_dataset(local)
    official, local = _compatible_compact_keys(official, local)
    official_labels = set(official.modes)
    local_labels = set(local.modes)
    official_families = _labels_by_family(official_labels)
    local_families = _labels_by_family(local_labels)
    balanced_families = {
        family
        for family in official_families.keys() & local_families.keys()
        if len(official_families[family]) == len(local_families[family])
    }
    # Component letters (a/b/...) and repeated-copy suffixes (_1/_2/...)
    # select a basis inside one fixed irrep subspace; they are not canonical
    # identities.  Exact-label differences are therefore semantic failures
    # only when their fixed k/irrep/site/site-irrep family or multiplicity also
    # differs.
    exact_missing = sorted(official_labels - local_labels)
    exact_extra = sorted(local_labels - official_labels)
    missing = sorted(
        label for label in exact_missing
        if _family_key(label) not in balanced_families
    )
    extra = sorted(
        label for label in exact_extra
        if _family_key(label) not in balanced_families
    )
    label_reassignments = [
        {
            "family": family,
            "official_labels": official_families[family],
            "local_labels": local_families[family],
        }
        for family in sorted(balanced_families)
        if set(official_families[family]) != set(local_families[family])
    ]
    try:
        mapping, atom_error, origin_shift = _atom_bijection_with_origin_shift(
            official.atoms,
            local.atoms,
            official.lattice,
            float(TOLERANCES["atom_cartesian_distance_angstrom"]),
        )
        mapping_error = None
    except ValueError as exc:
        mapping, atom_error, origin_shift, mapping_error = [], None, None, str(exc)

    common_families = sorted(official_families.keys() & local_families.keys())
    family_results = []
    maximum_angle = 0.0
    maximum_gram_error = 0.0
    maximum_unit_norm_error = 0.0
    overall_subspace: dict[str, Any] | None = None
    if mapping_error is None:
        for family in common_families:
            left_labels = official_families[family]
            right_labels = local_families[family]
            left_matrix = _cartesian_matrix(official, left_labels)
            right_matrix = _cartesian_matrix(local, right_labels, reorder=mapping)
            left_basis, left_rank = _orthonormal_basis(left_matrix)
            right_basis, right_rank = _orthonormal_basis(right_matrix)
            if left_rank != right_rank or left_rank == 0:
                angle = 90.0
                singular_values: list[float] = []
            else:
                singular = np.linalg.svd(left_basis.T @ right_basis, compute_uv=False)
                singular = np.clip(singular, -1.0, 1.0)
                angle = float(np.max(np.degrees(np.arccos(singular))))
                singular_values = [float(value) for value in singular]
            left_gram_eigs = np.linalg.eigvalsh(left_matrix.T @ left_matrix)
            right_gram_eigs = np.linalg.eigvalsh(right_matrix.T @ right_matrix)
            gram_error = (
                float(np.max(np.abs(np.sort(left_gram_eigs) - np.sort(right_gram_eigs))))
                if len(left_gram_eigs) == len(right_gram_eigs)
                else math.inf
            )
            left_norms = np.linalg.norm(left_matrix, axis=0)
            right_norms = np.linalg.norm(right_matrix, axis=0)
            unit_norm_error = float(
                max(
                    np.max(np.abs(left_norms - 1.0), initial=0.0),
                    np.max(np.abs(right_norms - 1.0), initial=0.0),
                )
            )
            maximum_angle = max(maximum_angle, angle)
            maximum_gram_error = max(maximum_gram_error, gram_error)
            maximum_unit_norm_error = max(maximum_unit_norm_error, unit_norm_error)
            family_results.append(
                {
                    "family": family,
                    "official_dimension": len(left_labels),
                    "local_dimension": len(right_labels),
                    "official_rank": left_rank,
                    "local_rank": right_rank,
                    "max_principal_angle_degrees": angle,
                    "singular_values": singular_values,
                    "gram_eigenvalue_max_abs_error": gram_error,
                    "unit_norm_max_abs_error": unit_norm_error,
                    "comparison": (
                        "global-sign"
                        if len(left_labels) == len(right_labels) == 1
                        else "Cartesian-subspace"
                    ),
                }
            )

        all_left_labels = sorted(official_labels)
        all_right_labels = sorted(local_labels)
        all_left = _cartesian_matrix(official, all_left_labels)
        all_right = _cartesian_matrix(local, all_right_labels, reorder=mapping)
        left_basis, left_rank = _orthonormal_basis(all_left)
        right_basis, right_rank = _orthonormal_basis(all_right)
        if left_rank == right_rank and left_rank:
            singular = np.clip(
                np.linalg.svd(left_basis.T @ right_basis, compute_uv=False),
                -1.0,
                1.0,
            )
            overall_angle = float(np.max(np.degrees(np.arccos(singular))))
            overall_singular = [float(value) for value in singular]
        else:
            overall_angle = 90.0
            overall_singular = []
        overall_subspace = {
            "official_column_count": len(all_left_labels),
            "local_column_count": len(all_right_labels),
            "official_rank": left_rank,
            "local_rank": right_rank,
            "max_principal_angle_degrees": overall_angle,
            "singular_values": overall_singular,
        }

    normfactor_error: float | None = None
    if compare_normfactors and not missing and not extra:
        differences = [
            abs(
                float(official.modes[official_families[family][0]].normfactor)
                - float(local.modes[local_families[family][0]].normfactor)
            )
            for family in sorted(balanced_families)
            if len(official_families[family]) == 1
            and official.modes[official_families[family][0]].normfactor is not None
            and local.modes[local_families[family][0]].normfactor is not None
        ]
        normfactor_error = max(differences, default=0.0)

    bound_error: float | None = None
    bound_mismatches: list[dict[str, Any]] = []
    bound_family_multiset_results: list[dict[str, Any]] = []
    bound_family_multiset_error: float | None = None
    if compare_amplitude_bounds and not missing and not extra:
        for label in sorted(official_labels & local_labels):
            left_bound = official.modes[label].amplitude_bound
            right_bound = local.modes[label].amplitude_bound
            if left_bound is None or right_bound is None:
                continue
            difference = abs(left_bound - right_bound)
            if difference > float(TOLERANCES["amplitude_bound_absolute"]):
                bound_mismatches.append(
                    {
                        "label": label,
                        "official": left_bound,
                        "local": right_bound,
                        "absolute_error": difference,
                    }
                )
        bound_error = max((item["absolute_error"] for item in bound_mismatches), default=0.0)
        for family in sorted(balanced_families):
            left_labels = official_families[family]
            right_labels = local_families[family]
            left_values = [official.modes[label].amplitude_bound for label in left_labels]
            right_values = [local.modes[label].amplitude_bound for label in right_labels]
            if any(value is None for value in (*left_values, *right_values)):
                continue
            left_sorted = sorted(float(value) for value in left_values if value is not None)
            right_sorted = sorted(float(value) for value in right_values if value is not None)
            error = max(
                (abs(left - right) for left, right in zip(left_sorted, right_sorted, strict=True)),
                default=0.0,
            )
            bound_family_multiset_results.append(
                {
                    "family": family,
                    "dimension": len(left_labels),
                    "max_sorted_multiset_abs_error": error,
                }
            )
        bound_family_multiset_error = max(
            (item["max_sorted_multiset_abs_error"] for item in bound_family_multiset_results),
            default=0.0,
        )

    amplitude_triplet_mismatches: list[dict[str, Any]] = []
    amplitude_triplet_missing: list[dict[str, str]] = []
    max_as_error: float | None = None
    max_ap_error: float | None = None
    max_dmax_error: float | None = None
    official_formula: dict[str, Any] | None = None
    local_formula: dict[str, Any] | None = None
    if compare_mode_amplitudes:
        official_formula = _amplitude_formula_audit(official)
        local_formula = _amplitude_formula_audit(local)
        as_errors = []
        ap_errors = []
        dmax_errors = []
        for label in sorted(official_labels & local_labels):
            left = official.modes[label]
            right = local.modes[label]
            values = (
                ("As", left.amplitude_supercell, right.amplitude_supercell),
                ("Ap", left.amplitude_parent, right.amplitude_parent),
                ("dmax_angstrom", left.dmax_angstrom, right.dmax_angstrom),
            )
            if any(left_value is None or right_value is None for _name, left_value, right_value in values):
                amplitude_triplet_missing.append(
                    {
                        "label": label,
                        "reason": "official or local As/Ap/dmax field is absent",
                    }
                )
                continue
            errors = {
                name: abs(float(left_value) - float(right_value))
                for name, left_value, right_value in values
            }
            as_errors.append(errors["As"])
            ap_errors.append(errors["Ap"])
            dmax_errors.append(errors["dmax_angstrom"])
            if (
                errors["As"] > float(TOLERANCES["mode_amplitude_absolute"])
                or errors["Ap"] > float(TOLERANCES["mode_amplitude_absolute"])
                or errors["dmax_angstrom"] > float(TOLERANCES["mode_dmax_angstrom"])
            ):
                amplitude_triplet_mismatches.append(
                    {
                        "label": label,
                        "official": {
                            "As": left.amplitude_supercell,
                            "Ap": left.amplitude_parent,
                            "dmax_angstrom": left.dmax_angstrom,
                        },
                        "local": {
                            "As": right.amplitude_supercell,
                            "Ap": right.amplitude_parent,
                            "dmax_angstrom": right.dmax_angstrom,
                        },
                        "absolute_errors": errors,
                    }
                )
        max_as_error = max(as_errors, default=0.0)
        max_ap_error = max(ap_errors, default=0.0)
        max_dmax_error = max(dmax_errors, default=0.0)

    failure_reasons = []
    inconclusive_reasons = []
    diagnostic_notes = []
    if label_reassignments:
        diagnostic_notes.append(
            f"{len(label_reassignments)} fixed mode families use different allowed "
            "component/copy basis labels"
        )
    if missing:
        failure_reasons.append(f"{len(missing)} official mode labels missing locally")
    if extra:
        failure_reasons.append(f"{len(extra)} extra local mode labels")
    if mapping_error:
        inconclusive_reasons.append(mapping_error)
    if maximum_angle > float(TOLERANCES["mode_principal_angle_degrees"]):
        failure_reasons.append(f"principal angle {maximum_angle:.6g} degrees exceeds tolerance")
    if (
        overall_subspace is not None
        and overall_subspace["max_principal_angle_degrees"]
        > float(TOLERANCES["mode_principal_angle_degrees"])
    ):
        failure_reasons.append(
            "overall Cartesian mode-space rank/angle differs: "
            f"rank {overall_subspace['official_rank']} vs {overall_subspace['local_rank']}, "
            f"angle {overall_subspace['max_principal_angle_degrees']:.6g} degrees"
        )
    if maximum_gram_error > float(TOLERANCES["gram_eigenvalue_absolute"]):
        failure_reasons.append(f"Gram eigenvalue error {maximum_gram_error:.6g} exceeds tolerance")
    if require_unit_norm and maximum_unit_norm_error > float(TOLERANCES["unit_norm_absolute"]):
        failure_reasons.append(f"unit-norm error {maximum_unit_norm_error:.6g} exceeds tolerance")
    if normfactor_error is not None and normfactor_error > float(TOLERANCES["mode_normfactor_angstrom_inverse"]):
        failure_reasons.append(f"normfactor error {normfactor_error:.6g} Angstrom^-1 exceeds tolerance")
    if (
        compare_amplitude_bounds
        and bound_family_multiset_error is not None
        and bound_family_multiset_error > float(TOLERANCES["amplitude_bound_absolute"])
    ):
        failure_reasons.append("amplitude-bound family multiset differs")
    elif bound_mismatches:
        if bound_family_multiset_error is not None:
            diagnostic_notes.append(
                f"{len(bound_mismatches)} amplitude bounds differ by label, while each "
                "family multiset agrees (allowed component/copy basis permutation)"
            )
    if amplitude_triplet_mismatches:
        failure_reasons.append(f"{len(amplitude_triplet_mismatches)} As/Ap/dmax triplets differ")
    if official_formula is not None and official_formula["status"] == "fail":
        failure_reasons.append("official As/Ap/dmax rows violate the declared formula")
    if local_formula is not None and local_formula["status"] == "fail":
        failure_reasons.append("local As/Ap/dmax rows violate the declared formula")
    if amplitude_triplet_missing:
        inconclusive_reasons.append(
            f"{len(amplitude_triplet_missing)} common modes lack a complete As/Ap/dmax triplet"
        )
    if official_formula is not None and official_formula["status"] == "inconclusive":
        inconclusive_reasons.append("official As/Ap/dmax formula audit lacks required evidence")
    if local_formula is not None and local_formula["status"] == "inconclusive":
        inconclusive_reasons.append("local As/Ap/dmax formula audit lacks required evidence")

    if failure_reasons:
        status = "fail"
    elif inconclusive_reasons:
        status = "inconclusive"
    else:
        status = "pass"

    return {
        "status": status,
        "official_mode_count": len(official_labels),
        "local_mode_count": len(local_labels),
        "missing_local_labels": missing,
        "extra_local_labels": extra,
        "official_atom_count": len(official.atoms),
        "local_atom_count": len(local.atoms),
        "max_species_periodic_mapping_error_angstrom": atom_error,
        "global_origin_shift_fractional_official_to_local": origin_shift,
        "mapping_error": mapping_error,
        "family_count": len(common_families),
        "max_principal_angle_degrees": maximum_angle,
        "max_gram_eigenvalue_abs_error": maximum_gram_error,
        "max_unit_norm_abs_error": maximum_unit_norm_error,
        "max_normfactor_abs_error_angstrom_inverse": normfactor_error,
        "max_amplitude_bound_abs_error": bound_error,
        "amplitude_bound_mismatches": bound_mismatches[:20],
        "amplitude_bound_family_multiset": {
            "comparison_policy": (
                "unordered within each fixed k/irrep/site-irrep family because degenerate "
                "components and repeated irrep copies have no canonical vector assignment"
            ),
            "max_abs_error": bound_family_multiset_error,
            "permutation_equivalent": bool(
                (bound_mismatches or label_reassignments)
                and bound_family_multiset_error is not None
                and bound_family_multiset_error
                <= float(TOLERANCES["amplitude_bound_absolute"])
            ),
            "families": bound_family_multiset_results,
        },
        "component_copy_label_reassignments": label_reassignments[:20],
        "diagnostics": diagnostic_notes,
        "mode_amplitude_comparison": {
            "enabled": compare_mode_amplitudes,
            "max_As_abs_error": max_as_error,
            "max_Ap_abs_error": max_ap_error,
            "max_dmax_abs_error_angstrom": max_dmax_error,
            "missing_triplets": amplitude_triplet_missing[:20],
            "mismatches": amplitude_triplet_mismatches[:20],
            "official_formula_audit": official_formula,
            "local_formula_audit": local_formula,
        },
        "reasons": [*failure_reasons, *inconclusive_reasons],
        "failure_reasons": failure_reasons,
        "inconclusive_reasons": inconclusive_reasons,
        "overall_cartesian_subspace": overall_subspace,
        "families": family_results,
    }


def _find_modes_html(folder: Path) -> Path:
    candidates = [path for path in folder.glob("*.html") if "complete modes" in path.name.casefold()]
    if len(candidates) != 1:
        raise ValueError(f"expected one Complete modes HTML in {folder}, found {len(candidates)}")
    return candidates[0]


