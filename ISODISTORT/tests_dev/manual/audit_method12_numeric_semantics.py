"""Signed, read-only numerical audit of saved Method 1/2 exports.

The older Method 1/2 audit proves candidate identities and mode counts.  This
audit asks a narrower but numerical question: do selected official and local
saved exports describe the same atomic structure and the same Cartesian mode
subspaces?  It deliberately does not mutate ``output_compare`` and does not
turn missing evidence into a pass.

Scientific conventions
----------------------

* Fractional positions are equivalent modulo integer translations.
* Atom correspondence is a species-preserving maximum bipartite matching in
  Cartesian distance, rather than CIF/file row order.
* Fractional displacement rows are converted with ``u_cart = u_frac @ L``
  where the rows of ``L`` are the direct-lattice vectors in Angstrom.
* One-dimensional modes are compared up to a global sign.  Multi-column mode
  families are compared through singular values of their orthonormal bases;
  the reported principal angle is therefore invariant under a basis rotation.
  Per-vector amplitude bounds in such a family are consequently compared as
  an unordered multiset: component/copy names do not canonically identify a
  basis vector inside a degenerate or repeated-irrep subspace.
* Official HTML rounds coordinates/mode components to five/four decimals, so
  every tolerance below is explicit and is part of the signed report.

The checked files are snapshots.  Hashing the production source records which
implementation was present during the audit; it does not falsely assert that
an old local snapshot was generated by that exact source revision.
"""

