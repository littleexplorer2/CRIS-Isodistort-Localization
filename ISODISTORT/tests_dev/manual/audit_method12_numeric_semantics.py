def _file_inventory(output_root: Path, cases: Iterable[dict[str, Any]]) -> list[Path]:
    paths = [SCRIPT_PATH, *PRODUCTION_SIGNATURE_FILES]
    for case in cases:
        if case.get("folder") is None:
            continue
        official, local = _case_paths(output_root, case)
        paths.extend(official / name for name in CORE_FILENAMES)
        paths.append(_find_modes_html(official))
        paths.extend(local / name for name in (*CORE_FILENAMES, "Complete modes details.txt"))
    return paths


def _signature_state(output_root: Path, cases: list[dict[str, Any]]) -> dict[str, Any]:
    files = []
    missing = []
    for path in _file_inventory(output_root, cases):
        if path.is_file():
            files.append({"path": str(path.resolve()), "sha256": _sha256(path), "bytes": path.stat().st_size})
        else:
            missing.append(str(path.resolve()))
    environment = {
        "python": platform.python_version(),
        "numpy": np.__version__,
        "pymatgen": _module_version("pymatgen"),
        "platform": platform.platform(),
    }
    material = {
        "schema": SCHEMA_VERSION,
        "files": files,
        "missing_files": missing,
        "case_matrix": cases,
        "tolerances": TOLERANCES,
        "environment": environment,
    }
    encoded = json.dumps(material, sort_keys=True, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    return {**material, "signature": hashlib.sha256(encoded).hexdigest()}


def _module_version(name: str) -> str:
    try:
        return version(name)
    except Exception:  # noqa: BLE001 - version evidence must not abort the audit
        return "unknown"


def _jsonable(value: Any) -> Any:
    if isinstance(value, dict):
        return {str(key): _jsonable(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_jsonable(item) for item in value]
    if isinstance(value, np.ndarray):
        return value.tolist()
    if isinstance(value, (np.integer, np.floating)):
        return value.item()
    if isinstance(value, Path):
        return str(value.resolve())
    if value is None or isinstance(value, (str, int, float, bool)):
        return value
    return str(value)


def _hash_records(paths: Iterable[Path]) -> list[dict[str, Any]]:
    records = []
    for path in sorted({item.resolve() for item in paths}, key=lambda item: str(item).casefold()):
        if not path.is_file():
            continue
        try:
            display = str(path.relative_to(WORKSPACE.resolve()))
        except ValueError:
            display = str(path)
        records.append({"path": display, "sha256": _sha256(path), "bytes": path.stat().st_size})
    return records


def _records_signature(records: list[dict[str, Any]]) -> str:
    encoded = json.dumps(records, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(encoded).hexdigest()


