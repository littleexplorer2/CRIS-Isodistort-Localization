"""Generate the bibliography and reading notes from the single source catalogue."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def tex(value):
    return str(value).replace('&', r'\&').replace('%', r'\%').replace('_', r'\_').replace('#', r'\#')


def main():
    rows = json.loads((ROOT / 'sources.json').read_text(encoding='utf-8'))['sources']
    bib = ['% Generated by audit/build_catalogue.py from sources.json. Do not edit by hand.']
    notes = ['# 注释书目', '', '由 `sources.json` 生成；仅在该文件维护书目和注释。', '',
             '“核验材料”说明本次实际检查层级；下载成功不等于全文审读，更不等于实现验证。', '']
    for row in rows:
        article = bool(row.get('journal'))
        fields = {
            'author': ' and '.join(row['authors']) if row.get('authors') else '{' + row['corporate_author'] + '}',
            'title': '{' + row['title'] + '}',
        }
        fields['year'] = str(row['year']) if row.get('year') else 'n.d.'
        for name in ('journal', 'volume', 'pages', 'doi'):
            if row.get(name):
                fields[name] = row[name]
        if not row.get('doi'):
            fields['url'] = row['url']
        if not article:
            fields['note'] = 'Accessed ' + row['accessed'] + '; ' + row['type'].replace('_', ' ')
        if row.get('copy_note'):
            fields['note'] = row['copy_note']
        bib.append('@' + ('article' if article else 'misc') + '{' + row['id'] + ',')
        for name, value in fields.items():
            # URL and DOI are consumed by url/natbib; do not put backslashes into URLs.
            escaped = str(value) if name in ('url', 'doi') else tex(value)
            bib.append('  ' + name + ' = {' + escaped + '},')
        bib.append('}\n')
        annotation = row['annotation']
        notes.extend([
            '## ' + row['id'], '',
            '[' + row['title'] + '](' + row.get('doi_url', row['url']) + ')', '',
            '- 作者/机构：' + '; '.join(row.get('authors', [row.get('corporate_author', '')])),
            '- 核验材料：' + annotation['reviewed_material'],
            '- 支持内容：' + annotation['supports'],
            '- 使用边界：' + annotation['limits'],
            '- 获取入口：[' + row['type'] + '](' + row['url'] + ')',
            '- 预定本地位置：`' + row['local_file'] + '`（实际可用性见下载清单）。', '',
        ])
    (ROOT / 'latex/references.bib').write_text('\n'.join(bib).rstrip() + '\n', encoding='utf-8')
    (ROOT / 'notes/ANNOTATED_SOURCES.md').write_text('\n'.join(notes), encoding='utf-8')
    print(f'Generated {len(rows)} bibliography entries and annotated source records.')


if __name__ == '__main__':
    main()
