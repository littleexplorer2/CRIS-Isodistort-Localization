def _ensure_isocore(cris_root: Path) -> None:
    iso_dir = cris_root / "ISODISTORT"
    if not iso_dir.is_dir():
        raise FileNotFoundError(f"ISODISTORT not found at {iso_dir}")
    text = str(iso_dir)
    if text not in sys.path:
        sys.path.insert(0, text)


def _hkl_transform_from_basis(basis: Sequence[Sequence[float]] | None) -> np.ndarray:
    mat = np.eye(3, dtype=np.float32)
    if not basis:
        return mat
    arr = np.asarray(basis, dtype=np.float32)
    if arr.shape == (3, 3):
        return arr
    return mat


def _parent_cell_count(basis: np.ndarray) -> int:
    det = abs(float(np.linalg.det(np.asarray(basis, dtype=float))))
    n = int(round(det))
    return max(n, 1)


def compute_gd_bundle(
    *,
    cif: Path,
    k_label: str,
    irrep: str,
    opd: str,
    k_params: list[str],
    nmod: int,
    cris_root: Path,
    language: str = "en",
) -> GdBundle:
    _ensure_isocore(cris_root)
    from isocore.api import IsoDistort
    from isocore.io.distortion_formats import cart_normalized_mode_matrix

    cif = Path(cif)
    if not cif.is_file():
        raise FileNotFoundError(cif)

    iso = IsoDistort(language=language)
    iso.set_distortion_types(["strain", "displacive"])
    iso.set_distortion_scope({
        "displacive": ["*"],
        "occupational": [],
        "strain": [],
        "magnetic": [],
        "rotational": [],
    })
    iso.load_structure(cif)
    subs = iso.list_subgroups_at(
        k_label, irrep, k_parameters=list(k_params), generate_if_missing=False,
    )
    target = next(
        (
            s for s in subs
            if s.irrep_label == irrep and str(s.opd_symbol).upper() == opd.upper()
        ),
        None,
    )
    if target is None:
        available = sorted({f"{s.irrep_label}:{s.opd_symbol}" for s in subs})
        raise RuntimeError(
            f"{irrep} {opd} not in Method-2 list at {k_label} "
            f"{k_params}; have {available[:20]}"
        )
    iso.search_method_2(
        target.index,
        candidates=subs,
        number_of_independent_modulations=int(nmod),
    )
    sc = iso._supercell_for_subgroup(target)
    disp_map = dict(getattr(iso, "mode_displacements_sc", None) or {})
    labels = dict(getattr(iso, "_mode_label_overrides", None) or {})
    ordered_keys: list[str] = []
    for mode in iso.distortion_modes or []:
        key = iso._mode_session_key(mode)
        if key in disp_map and key not in ordered_keys:
            ordered_keys.append(key)
    for key in disp_map:
        if key not in ordered_keys:
            ordered_keys.append(key)
    if not ordered_keys:
        raise RuntimeError("Method 2 returned no supercell displacive modes")

    n_cells = _parent_cell_count(target.basis_vectors or np.eye(3))
    names: list[str] = []
    vectors: list[np.ndarray] = []
    norms: list[float] = []
    bounds: list[float] = []
    lattice = np.asarray(sc.lattice.matrix, dtype=float)
    for key in ordered_keys:
        raw = np.asarray(disp_map[key], dtype=float)
        if raw.shape != (len(sc), 3):
            raise RuntimeError(
                f"mode {key} has shape {raw.shape}, supercell has {len(sc)} atoms"
            )
        scaled, maxamp = cart_normalized_mode_matrix(
            raw, lattice, centering_mult=n_cells
        )
        names.append(labels.get(key) or key)
        vectors.append(np.asarray(scaled, dtype=np.float32))
        # cart-normalized vectors already have primitive Cartesian RMS = 1 Å
        # per unit amplitude, so the notebook's extra scale is identity.
        norms.append(1.0)
        bounds.append(float(maxamp))

    mode_frac = np.stack(vectors, axis=0)
    base_frac = np.asarray(sc.frac_coords, dtype=np.float32)
    species = [str(site.species_string) for site in sc]
    parent_sg = int((iso.symmetry_info or {}).get("space_group_number") or 0)
    parent_sym = str(
        (iso.symmetry_info or {}).get("space_group_symbol") or parent_sg
    )
    hkl_t = _hkl_transform_from_basis(target.basis_vectors)
    meta = {
        "cif": str(cif),
        "k_label": k_label,
        "k_params": list(k_params),
        "irrep": irrep,
        "opd": opd,
        "nmod": int(nmod),
        "parent_sg": parent_sg,
        "parent_symbol": parent_sym,
        "child_sg": int(target.space_group_number or 0),
        "child_symbol": str(target.space_group_symbol or ""),
        "basis": [list(map(float, row)) for row in (target.basis_vectors or [])],
        "origin": list(map(float, target.origin or [0, 0, 0])),
        "n_modes": len(names),
        "n_atoms": len(species),
        "parent_cells_in_supercell": n_cells,
        "maxamp_convention": "sqrt(N_parent_cells) after primitive Cartesian RMS = 1",
        "norm_factors": "1 (mode vectors already cart-normalized)",
    }
    return GdBundle(
        names=names,
        norm_factors=np.asarray(norms, dtype=np.float32),
        max_bounds=np.asarray(bounds, dtype=np.float32),
        species=species,
        base_frac=base_frac,
        mode_frac=mode_frac,
        lattice=np.asarray(lattice, dtype=np.float32),
        hkl_transform=hkl_t,
        parent_symbol=parent_sym,
        irrep=irrep,
        opd=opd,
        metadata=meta,
    )


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--cif", type=Path, default=DEFAULT_CIF)
    p.add_argument("--k", dest="k_label", default="LD")
    p.add_argument("--k-params", nargs="+", default=["1/6"])
    p.add_argument("--irrep", default="LD1")
    p.add_argument("--opd", default="C1")
    p.add_argument("--nmod", type=int, default=0)
    p.add_argument("--cris", type=Path, default=DEFAULT_CRIS)
    p.add_argument(
        "--out",
        type=Path,
        default=None,
        help="Output directory (default: generated/{irrep}_{opd})",
    )
    p.add_argument(
        "--prefix",
        default=None,
        help="File prefix (default: {irrep}_{opd})",
    )
    p.add_argument(
        "--install-alris",
        action="store_true",
        default=True,
        help="Also write {prefix}_alris_functions.py next to this script (notebook import).",
    )
    p.add_argument(
        "--no-install-alris",
        action="store_false",
        dest="install_alris",
    )
    return p


def main(argv: Sequence[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    prefix = args.prefix or f"{args.irrep}_{args.opd}"
    out_dir = args.out or (GD_ROOT / "generated" / prefix)
    install = (GD_ROOT / f"{prefix}_alris_functions.py") if args.install_alris else None
    bundle = compute_gd_bundle(
        cif=args.cif,
        k_label=args.k_label,
        irrep=args.irrep,
        opd=args.opd,
        k_params=list(args.k_params),
        nmod=int(args.nmod),
        cris_root=args.cris,
    )
    problems = check_bundle(bundle)
    if problems:
        raise SystemExit("bundle failed checks: " + "; ".join(problems))
    written = write_gd_bundle(out_dir, prefix, bundle, install_alris=install)
    print(f"wrote {bundle.metadata['n_modes']} modes, "
          f"{bundle.metadata['n_atoms']} atoms -> {out_dir}")
    for key, path in written.items():
        print(f"  {key}: {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
