def _no_space(text: str) -> str:
    return re.sub(r"\s+", "", str(text).strip()) or "mode"


def write_mario_mode_names(path: Path, names: Sequence[str]) -> None:
    path.write_text("".join(f"{_no_space(n)}\n" for n in names), encoding="utf-8")


def write_comma_row(path: Path, values: Sequence[float]) -> None:
    path.write_text(
        ",".join(f"{float(v):.8g}" for v in values) + "\n",
        encoding="utf-8",
    )


def write_displacive_modes(path: Path, names: Sequence[str]) -> None:
    lines = [f"{i} {_no_space(name)}" for i, name in enumerate(names, start=1)]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _py_float_array(name: str, arr: np.ndarray, indent: str = "") -> str:
    arr = np.asarray(arr, dtype=np.float32)
    flat = ", ".join(f"{float(x):.8g}" for x in arr.ravel())
    return (
        f"{indent}{name} = np.array([{flat}], dtype=np.float32)"
        f".reshape{tuple(int(n) for n in arr.shape)}\n"
    )


def _reciprocal_lattice(lattice: np.ndarray) -> np.ndarray:
    """Evaluate the existing row-lattice reciprocal in the GD storage dtype."""
    try:
        with np.errstate(over="ignore", invalid="ignore", divide="ignore"):
            reciprocal = 2.0 * math.pi * np.linalg.inv(lattice).T
    except np.linalg.LinAlgError as exc:
        raise ValueError("lattice must be nonsingular in float32") from exc
    if not np.isfinite(reciprocal).all():
        raise ValueError("reciprocal lattice must be finite in float32")
    return reciprocal


