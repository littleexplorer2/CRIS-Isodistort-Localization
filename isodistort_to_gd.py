def transform_list_hkl_p63_p65(hkl_list):
    """Map parent HKL onto the child supercell (historical function name)."""
    hkl = tf.cast(tf.convert_to_tensor(hkl_list), tf.float32)
    if hkl.shape.rank == 1:
        hkl = tf.reshape(hkl, (1, 3))
    return tf.matmul(hkl, _HKL_T_TF)


def atom_position_list(*amplitudes):
    """Return child-cell fractional coordinates, differentiable in ``amplitudes``."""
    if len(amplitudes) != N_MODES:
        raise ValueError(f"expected {N_MODES} amplitudes, got {len(amplitudes)}")
    amps = tf.stack([tf.cast(a, tf.float32) for a in amplitudes])
    amps = tf.reshape(amps, (N_MODES,))
    delta = tf.tensordot(amps, _MODE_TF, axes=[[0], [0]])
    return _BASE_TF + delta


def _form_factors(hkl):
    qvec = tf.matmul(tf.cast(hkl, tf.float32), _RECIP_TF)
    s2 = tf.reduce_sum(qvec * qvec, axis=1, keepdims=True) / tf.constant(
        (16.0 * np.pi ** 2), dtype=tf.float32
    )
    expo = tf.exp(-tf.expand_dims(_FF_B_TF, 0) * tf.expand_dims(s2, 2))
    ff = tf.reduce_sum(tf.expand_dims(_FF_A_TF, 0) * expo, axis=2)
    return ff + tf.expand_dims(_FF_C_TF, 0)


def get_structure_factors(hkl_list, struct):
    """F(hkl) = Σ_j f_j(|Q|) exp(2πi h·r_j) on the child cell."""
    hkl = tf.cast(tf.convert_to_tensor(hkl_list), tf.float32)
    xyz = tf.cast(tf.convert_to_tensor(struct), tf.float32)
    phase = (2.0 * np.pi) * tf.matmul(hkl, tf.transpose(xyz))
    ff = _form_factors(hkl)
    real = tf.reduce_sum(ff * tf.cos(phase), axis=1)
    imag = tf.reduce_sum(ff * tf.sin(phase), axis=1)
    return tf.complex(real, imag)


